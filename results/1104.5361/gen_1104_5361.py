def _candidate_from_ranked(inst: dict, ranked) -> list[int]:
    allowed = set(_allowed_vertices(inst))
    result = [inst["marked"]]
    for v in ranked:
        if v in allowed and v not in result:
            result.append(v)
            if len(result) == inst["required_size"]:
                break
    if len(result) < inst["required_size"]:
        for v in sorted(allowed):
            if v not in result:
                result.append(v)
                if len(result) == inst["required_size"]:
                    break
    return sorted(result)


def _attack_degree(inst: dict):
    degree = {v: 0 for v in inst["nonterminals"]}
    for u, v in inst["edges"]:
        if u in degree:
            degree[u] += 1
        if v in degree:
            degree[v] += 1
    target_degree = degree[inst["marked"]]
    ranked = sorted(degree, key=lambda v: (abs(degree[v] - target_degree),
                                            -degree[v], v))
    return _candidate_from_ranked(inst, ranked)


def _attack_terminal_distance(inst: dict):
    adjacency = {}
    for u, v in inst["edges"]:
        adjacency.setdefault(u, []).append(v)
        adjacency.setdefault(v, []).append(u)
    dist = {inst["sink"]: 0}
    queue = deque([inst["sink"]])
    while queue:
        u = queue.popleft()
        for v in adjacency.get(u, ()):
            if v not in dist:
                dist[v] = dist[u] + 1
                queue.append(v)
    ranked = sorted(inst["nonterminals"], key=lambda v: (dist.get(v, 10**9), v))
    return _candidate_from_ranked(inst, ranked)


