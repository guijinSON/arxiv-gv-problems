def _attack_cipher_blind(inst: dict):
    q, m, r = inst["q"], inst["tree_size"], inst["r"]
    visible_block = inst["marked"] // q
    apparent_tree, local = divmod(visible_block, m)
    ranked = []
    for tree in range(r):
        if tree != apparent_tree:
            ranked.append(q * (tree * m))
    for _ in range(inst["depth"]):
        if local == 0:
            break
        sibling = local + 1 if local % 2 == 1 else local - 1
        ranked.append(q * (apparent_tree * m + sibling))
        local = (local - 1) // 2
    return _candidate_from_ranked(inst, ranked)


def _dinic_reference(inst: dict):
    """Solve via vertex splitting and Dinic; return (answer, statistics)."""
    marked = inst["marked"]
    original_vertices = [inst["source"], inst["sink"], *inst["nonterminals"]]
    original_vertices = [v for v in original_vertices if v != marked]
    index = {v: i for i, v in enumerate(original_vertices)}
    network_n = 2 * len(original_vertices) + 2
    super_source = network_n - 2
    super_sink = network_n - 1
    graph = [[] for _ in range(network_n)]
    operations = 0

    def add_edge(u, v, cap):
        graph[u].append([v, len(graph[v]), cap])
        graph[v].append([u, len(graph[u]) - 1, 0])

    inf = len(original_vertices) + 1
    protected = set(inst["X"]) | set(inst["Y"])
    for v, i in index.items():
        add_edge(2 * i, 2 * i + 1, inf if v in protected else 1)
    for u, v in inst["edges"]:
        if u == marked or v == marked:
            continue
        add_edge(2 * index[u] + 1, 2 * index[v], inf)
        add_edge(2 * index[v] + 1, 2 * index[u], inf)
    for x in inst["X"]:
        if x != marked:
            add_edge(super_source, 2 * index[x], inf)
    for y in inst["Y"]:
        if y != marked:
            add_edge(2 * index[y] + 1, super_sink, inf)

    flow = 0
    target_limit = inst["required_size"]
    bfs_rounds = 0
    augmentations = 0
    while flow < target_limit:
        bfs_rounds += 1
        level = [-1] * network_n
        level[super_source] = 0
        queue = deque([super_source])
        while queue:
            u = queue.popleft()
            for edge in graph[u]:
                operations += 1
                if edge[2] and level[edge[0]] < 0:
                    level[edge[0]] = level[u] + 1
                    queue.append(edge[0])
        if level[super_sink] < 0:
            break
        ptr = [0] * network_n

        def dfs(u, pushed):
            nonlocal operations
            if u == super_sink:
                return pushed
            while ptr[u] < len(graph[u]):
                edge = graph[u][ptr[u]]
                operations += 1
                if edge[2] and level[edge[0]] == level[u] + 1:
                    sent = dfs(edge[0], min(pushed, edge[2]))
                    if sent:
                        edge[2] -= sent
                        graph[edge[0]][edge[1]][2] += sent
                        return sent
                ptr[u] += 1
            return 0

        while flow < target_limit:
            sent = dfs(super_source, target_limit - flow)
            if not sent:
                break
            flow += sent
            augmentations += 1

    # The final failed BFS leaves the residual reachable side in ``level``.
    cut = []
    if flow == inst["required_size"] - 1 and level[super_sink] < 0:
        for v, i in index.items():
            if v not in protected and level[2 * i] >= 0 and level[2 * i + 1] < 0:
                cut.append(v)
    candidate = sorted([marked] + cut)
    return candidate, {
        "flow": flow,
        "edge_scan_operations": operations,
        "bfs_rounds": bfs_rounds,
        "augmentations": augmentations,
        "network_vertices": network_n,
    }


def _relabel_instance(inst: dict, rng: random.Random, reorder: bool = False) -> dict:
    vertices = [inst["source"], inst["sink"], *inst["nonterminals"]]
    shuffled = list(vertices)
    rng.shuffle(shuffled)
    mapping = dict(zip(vertices, shuffled))
    out = dict(inst)
    out["source"] = mapping[inst["source"]]
    out["sink"] = mapping[inst["sink"]]
    out["X"] = [mapping[v] for v in inst["X"]]
    out["Y"] = [mapping[v] for v in inst["Y"]]
    out["marked"] = mapping[inst["marked"]]
    out["nonterminals"] = [mapping[v] for v in inst["nonterminals"]]
    out["allowed_vertices"] = [mapping[v] for v in inst["allowed_vertices"]]
    out["candidate_pool"] = [mapping[v] for v in inst["candidate_pool"]]
    out["edges"] = [[mapping[u], mapping[v]] for u, v in inst["edges"]]
    if reorder:
        rng.shuffle(out["edges"])
    out["answer"] = [mapping[v] for v in inst["answer"]]
    out["_explicit_only"] = True
    return out


def _answer_text(answer) -> str:
    return "<answer>" + ", ".join(map(str, answer)) + "</answer>"


def selftest() -> dict:
    """Run G1--G9 and return a fully JSON-serialisable measurement report."""
    report = {"paper": "1104.5361", "track": TRACK,
              "shipping_difficulty": SHIPPING_DIFFICULTY}

    # G1: all named presets and several independent seeds.
    g1_ok = 0
    g1_total = 0
    for preset, params in DIFFICULTY.items():
        for seed in range(3):
            inst = make_instance(seed=seed, **params)
            ok, why = verify(inst, inst["answer"])
            g1_total += 1
            if ok:
                g1_ok += 1
            else:
                raise AssertionError((preset, seed, why))
            if json.loads(json.dumps(inst["answer"])) != inst["answer"]:
                raise AssertionError("answer is not JSON-native")
    report["G1_planted_verifies"] = {
        "pass": g1_ok == g1_total, "verified": g1_ok, "attempts": g1_total}

    shipping = DIFFICULTY[SHIPPING_DIFFICULTY]
    inst = make_instance(seed=101, **shipping)
    planted = list(inst["answer"])
    corruptions = {}
    corruptions["empty"] = []
    corruptions["drop_one"] = planted[:-1]
    corruptions["duplicate_one"] = planted[:-1] + [planted[0]]
    corruptions["out_of_range"] = planted[:-1] + [inst["q"] * inst["base_count"] + 7]
    replacement = next(v for v in _allowed_vertices(inst)
                       if v not in planted and v != inst["marked"])
    replace_at = next(i for i, v in enumerate(planted) if v != inst["marked"])
    swapped = list(planted)
    swapped[replace_at] = replacement
    corruptions["replace_one"] = swapped
    reasons = {}
    for name, candidate in corruptions.items():
        ok, why = verify(inst, candidate)
        if ok:
            raise AssertionError(f"corruption {name} verified")
        reasons[name] = why
    distinct_reasons = len(set(reasons.values()))
    report["G2_rejects_corruption"] = {
        "pass": distinct_reasons == len(corruptions),
        "rejected": len(corruptions), "distinct_reasons": distinct_reasons,
        "reasons": reasons,
    }

    model_style = ("I used the tree frontier.\n```text\n"
                   + _answer_text(inst["answer"])
                   + "\n```\nThose are the requested labels.")
    parsed = parse_answer(model_style)
    roundtrip_ok = parsed == inst["answer"] and verify(inst, parsed)[0]
    report["G3_round_trip"] = {
        "pass": roundtrip_ok, "parsed_elements": len(parsed or [])}

    # G4: samples are already exact-size, distinct, allowed, and marked-containing.
    guess_rng = random.Random(730_041)
    guess_total = 200_000
    guess_hits = 0
    for _ in range(guess_total):
        candidate = random_candidate(inst, guess_rng)
        guess_hits += int(verify(inst, candidate)[0])
    guess_probability = guess_hits / guess_total
    report["G4_guess_resistance"] = {
        "pass": guess_probability < 1e-6,
        "hits": guess_hits, "total": guess_total,
        "observed_probability": guess_probability,
        "candidate_space": search_space(inst),
        "sampling_prior": "uniform exact-size allowed sets containing marked",
    }

    # G6 and Track-B reference algorithm, all at the shipping preset.
    attack_names = [
        "outlier_same_degree",
        "greedy_closest_to_Y",
        "random_restart_256",
        "cipher_blind_heap_ansatz",
        "local_neighbourhood_ansatz",
    ]
    attack_success = {name: 0 for name in attack_names}
    reference_success = 0
    reference_seconds = []
    reference_ops = []
    reference_rounds = []
    for seed in range(8):
        test_inst = make_instance(seed=20_000 + seed, **shipping)
        candidates = {
            "outlier_same_degree": _attack_degree(test_inst),
            "greedy_closest_to_Y": _attack_terminal_distance(test_inst),
            "cipher_blind_heap_ansatz": _attack_cipher_blind(test_inst),
            "local_neighbourhood_ansatz": _attack_local(test_inst),
        }
        rr_rng = random.Random(90_000 + seed)
        rr_solved = False
        for _ in range(256):
            if verify(test_inst, random_candidate(test_inst, rr_rng))[0]:
                rr_solved = True
                break
        attack_success["random_restart_256"] += int(rr_solved)
        for name, candidate in candidates.items():
            attack_success[name] += int(verify(test_inst, candidate)[0])

        t0 = time.perf_counter()
        reference_answer, stats = _dinic_reference(test_inst)
        elapsed = time.perf_counter() - t0
        reference_success += int(verify(test_inst, reference_answer)[0])
        reference_seconds.append(elapsed)
        reference_ops.append(stats["edge_scan_operations"])
        reference_rounds.append(stats["bfs_rounds"])

    attacks = {name: {"successes": attack_success[name], "attempts": 8}
               for name in attack_names}
    reference = {
        "name": "vertex splitting plus Dinic max flow after deleting marked",
        "complexity": "O(V^2 E) worst-case",
        "wall_clock_sec": round(sum(reference_seconds) / len(reference_seconds), 6),
        "max_wall_clock_sec": round(max(reference_seconds), 6),
        "operations": round(sum(reference_ops) / len(reference_ops)),
        "max_operations": max(reference_ops),
        "bfs_rounds": round(sum(reference_rounds) / len(reference_rounds), 3),
        "successes": reference_success,
        "attempts": 8,
        "solves": f"{reference_success}/8, as expected",
    }
    report["G6_adversary_panel"] = {
        "pass": all(v["successes"] == 0 for v in attacks.values()),
        "attacks": attacks,
        "reference_algorithm": reference,
    }

    exact_valid = _exact_solution_count(inst)
    candidate_space = search_space(inst)
    report["G5_density_and_baseline"] = {
        "pass": exact_valid > 0 and reference_success == 8,
        "shipping_exact_valid_count": exact_valid,
        "shipping_candidate_space": candidate_space,
        "shipping_solution_density": exact_valid / candidate_space,
        "sample_hits": guess_hits,
        "sample_total": guess_total,
        "sampled_density": guess_probability,
        "baseline_wall_clock_sec": reference["wall_clock_sec"],
        "baseline_edge_scan_operations": reference["operations"],
        "baseline_bfs_rounds": reference["bfs_rounds"],
    }

    doubled_params = dict(shipping)
    doubled_params["n"] += 1
    doubled_params["q"] += 1
    doubled = make_instance(seed=303, **doubled_params)
    doubled_ok, doubled_why = verify(doubled, doubled["answer"])
    report["G7_scales"] = {
        "pass": doubled_ok and len(doubled["nonterminals"]) > 1.9 * len(inst["nonterminals"]),
        "shipping_vertices": len(inst["nonterminals"]) + 2,
        "larger_vertices": len(doubled["nonterminals"]) + 2,
        "size_ratio": len(doubled["nonterminals"]) / len(inst["nonterminals"]),
        "answer_elements_before": len(inst["answer"]),
        "answer_elements_after": len(doubled["answer"]),
        "verify_reason": doubled_why,
    }

    invariant_checks = 0
    transformed_verify = 0
    original_keys = []
    for seed in range(20):
        base = make_instance(seed=40_000 + seed, **DIFFICULTY["easy"])
        key = canonical_key(base)
        original_keys.append(key)
        rrng = random.Random(50_000 + seed)
        relabelled = _relabel_instance(base, rrng, reorder=False)
        reordered = dict(base)
        reordered["edges"] = list(reversed(base["edges"]))
        swapped = dict(base)
        swapped["X"], swapped["Y"] = list(base["Y"]), list(base["X"])
        relabelled_reordered = dict(relabelled)
        relabelled_reordered["edges"] = list(reversed(relabelled["edges"]))
        relabelled_swapped = dict(relabelled)
        relabelled_swapped["X"], relabelled_swapped["Y"] = (
            list(relabelled["Y"]), list(relabelled["X"]))
        reordered_swapped = dict(reordered)
        reordered_swapped["X"], reordered_swapped["Y"] = (
            list(base["Y"]), list(base["X"]))
        all_three = dict(relabelled_reordered)
        all_three["X"], all_three["Y"] = (
            list(relabelled_reordered["Y"]), list(relabelled_reordered["X"]))
        variants = [relabelled, reordered, swapped, relabelled_reordered,
                    relabelled_swapped, reordered_swapped, all_three]
        for transformed in variants:
            tok, _ = verify(transformed, transformed["answer"])
            transformed_verify += int(tok)
            invariant_checks += int(canonical_key(transformed) == key)
    distinct_keys = len(set(original_keys))
    report["G8_canonical_key"] = {
        "pass": invariant_checks == 140 and transformed_verify == 140
                and distinct_keys == 20,
        "invariance_passed": invariant_checks,
        "invariance_attempts": 140,
        "transformed_witnesses_verified": transformed_verify,
        "transformed_witness_attempts": 140,
        "distinct_unrelated_keys": distinct_keys,
        "distinctness_attempts": 20,
        "transformations": ["vertex relabelling", "edge reordering", "X-Y swap",
                            "their composition"],
    }

    size_samples = [make_instance(seed=s, **shipping)["answer"] for s in range(20)]
    answer_chars = max(len(json.dumps(a)) for a in size_samples)
    answer_elements = max(len(a) for a in size_samples)
    answer_tokens = (answer_chars + 3) // 4
    intended_operations = 96
    hinted = G9_ARMS["hinted"]
    placebo = G9_ARMS["placebo"]
    h_rate = hinted["solved"] / hinted["attempts"] if hinted["attempts"] else 0.0
    p_rate = placebo["solved"] / placebo["attempts"] if placebo["attempts"] else 0.0
    within_caps = answer_chars <= 2000 and answer_elements <= 256 and intended_operations <= 300
    report["G9_no_tool_suitability"] = {
        "pass": within_caps,
        "arms": G9_ARMS,
        "hinted_minus_placebo": h_rate - p_rate,
        "hinted_verdict": ("too_easy" if hinted["solved"] else "hardened")
                           if hinted["attempts"] else "not_yet_run",
        "answer_chars": answer_chars,
        "answer_tokens": answer_tokens,
        "answer_elements": answer_elements,
        "intended_route_operations": intended_operations,
        "caps": {"chars": 2000, "elements": 256, "operations": 300},
    }

    gates = [v for k, v in report.items() if k.startswith("G")]
    report["all_passed"] = all(g.get("pass") for g in gates)
    return report


