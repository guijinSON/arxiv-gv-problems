def parse_answer(text: str):
    """Parse a tagged comma-separated integer set, tolerating surrounding prose."""
    if not isinstance(text, str):
        return None
    matches = re.findall(r"<answer\b[^>]*>(.*?)</answer>", text,
                         flags=re.IGNORECASE | re.DOTALL)
    if not matches:
        return None
    body = matches[-1].strip()
    body = re.sub(r"^```(?:json|text)?\s*|\s*```$", "", body,
                  flags=re.IGNORECASE | re.DOTALL).strip()
    if body.startswith("[") and body.endswith("]"):
        body = body[1:-1].strip()
    if not body:
        return []
    pieces = [p.strip() for p in body.split(",")]
    if any(not re.fullmatch(r"[+-]?\d+", p) for p in pieces):
        return None
    try:
        return [int(p) for p in pieces]
    except (TypeError, ValueError, OverflowError):
        return None


def _decode_vertex(inst: dict, label: int):
    """Return (logical base index, subdivision position), or None."""
    if not isinstance(label, int) or isinstance(label, bool) or label < 0:
        return None
    q = inst["q"]
    encoded, pos = divmod(label, q)
    if encoded >= inst["base_count"]:
        return None
    j = (inst["a_inv"] * (encoded - inst["b"])) % inst["base_count"]
    local = j % inst["tree_size"]
    if pos == 0:
        return j, pos
    if local == 0:
        return None
    length = _edge_length(j, inst["ell_a"], inst["ell_b"],
                          inst["ell_mod"], q)
    if pos >= length:
        return None
    return j, pos


def _formula_separates(inst: dict, cut: set[int]) -> bool:
    """Exact reachability test on the promised subdivided binary-tree graph."""
    selected = set()
    for label in cut:
        decoded = _decode_vertex(inst, label)
        if decoded is None:
            return False
        selected.add(decoded[0])

    height = inst["n"]
    tree_size = inst["tree_size"]
    first_leaf = (1 << height) - 1

    def covered(offset: int, local: int) -> bool:
        if offset + local in selected:
            return True
        if local >= first_leaf:
            return False
        return (covered(offset, 2 * local + 1)
                and covered(offset, 2 * local + 2))

    for tree in range(inst["r"]):
        if not covered(tree * tree_size, 0):
            return False
    return True


def _explicit_separates(inst: dict, cut: set[int]) -> bool:
    adjacency = {}
    for u, v in inst["edges"]:
        adjacency.setdefault(u, []).append(v)
        adjacency.setdefault(v, []).append(u)
    targets = set(inst["Y"])
    stack = [x for x in inst["X"] if x not in cut]
    seen = set(stack)
    while stack:
        u = stack.pop()
        if u in targets:
            return False
        for v in adjacency.get(u, ()):
            if v not in cut and v not in seen:
                seen.add(v)
                stack.append(v)
    return True


def verify(inst: dict, answer) -> tuple[bool, str]:
    """Check any valid separator; the planted answer is never consulted."""
    if not isinstance(answer, list):
        return False, "answer must be a list of integer vertex labels"
    if not answer:
        return False, "answer must be a nonempty list"
    if len(answer) != inst["required_size"]:
        return False, f"wrong number of labels: expected {inst['required_size']}"
    if any(not isinstance(v, int) or isinstance(v, bool) for v in answer):
        return False, "every vertex label must be an integer"
    if len(set(answer)) != len(answer):
        return False, "duplicate vertex labels are forbidden"
    if inst["marked"] not in answer:
        return False, "the marked vertex is missing"
    forbidden = set(inst["X"]) | set(inst["Y"])
    if any(v in forbidden for v in answer):
        return False, "a separator may not contain a vertex of X or Y"

    if inst.get("_explicit_only"):
        allowed = set(inst["nonterminals"])
        if any(v not in allowed for v in answer):
            return False, "unknown nonterminal vertex label"
        separates = _explicit_separates(inst, set(answer))
    else:
        if any(_decode_vertex(inst, v) is None for v in answer):
            return False, "unknown nonterminal vertex label"
        separates = _formula_separates(inst, set(answer))
    if not separates:
        return False, "deleting these vertices leaves an X-Y path"
    return True, "ok"


def _allowed_vertices(inst: dict) -> list[int]:
    if "allowed_vertices" in inst:
        return inst["allowed_vertices"]
    forbidden = set(inst["X"]) | set(inst["Y"])
    return [v for v in inst["nonterminals"] if v not in forbidden]


def random_candidate(inst: dict, rng: random.Random):
    """Sample uniformly from the structure-aware bounded certificate language."""
    marked = inst["marked"]
    pool = inst.get("candidate_pool")
    if pool is None:
        pool = [v for v in _allowed_vertices(inst) if v != marked]
    chosen = rng.sample(pool, inst["required_size"] - 1)
    return sorted([marked] + chosen)


def search_space(inst: dict):
    allowed_count = len(_allowed_vertices(inst))
    return math.comb(allowed_count - 1, inst["required_size"] - 1)


def enumerate_all(inst: dict):
    space = search_space(inst)
    if space > 100_000:
        return None
    allowed = [v for v in _allowed_vertices(inst) if v != inst["marked"]]
    count = 0
    for tail in itertools.combinations(allowed, inst["required_size"] - 1):
        ok, _ = verify(inst, [inst["marked"], *tail])
        count += int(ok)
    return count


def _exact_solution_count(inst: dict) -> int:
    """Count minimum frontiers containing marked, using the construction proof."""
    e_marked = inst["marked"] // inst["q"]
    marked_j = (inst["a_inv"] * (e_marked - inst["b"])) % inst["base_count"]
    local = marked_j % inst["tree_size"]
    offset = marked_j - local
    count = 1
    for _ in range(inst["depth"]):
        sibling_local = local + 1 if local % 2 == 1 else local - 1
        sibling_j = offset + sibling_local
        count *= _edge_length(sibling_j, inst["ell_a"], inst["ell_b"],
                              inst["ell_mod"], inst["q"])
        local = (local - 1) // 2
    return count


def _tree_component_digest(nodes, adjacency, colors) -> bytes:
    """AHU-style canonical digest of one unrooted colored tree."""
    if len(nodes) == 1:
        centers = list(nodes)
    else:
        degree = {v: sum(w in nodes for w in adjacency.get(v, ())) for v in nodes}
        leaves = deque(v for v in nodes if degree[v] <= 1)
        remaining = len(nodes)
        while remaining > 2:
            batch = len(leaves)
            remaining -= batch
            for _ in range(batch):
                v = leaves.popleft()
                for w in adjacency.get(v, ()):
                    if w in degree and degree[w] > 0:
                        degree[w] -= 1
                        if degree[w] == 1:
                            leaves.append(w)
                degree[v] = 0
        centers = list(leaves) if leaves else [next(iter(nodes))]

    def rooted(v, parent):
        child_hashes = [rooted(w, v) for w in adjacency.get(v, ())
                        if w != parent and w in nodes]
        child_hashes.sort()
        payload = bytes(colors[v]) + b"(" + b"".join(child_hashes) + b")"
        return hashlib.sha256(payload).digest()

    if len(centers) == 1:
        return hashlib.sha256(b"one" + rooted(centers[0], None)).digest()
    c1, c2 = centers[:2]
    halves = sorted([rooted(c1, c2), rooted(c2, c1)])
    return hashlib.sha256(b"two" + halves[0] + halves[1]).digest()


def _canonical_orientation(inst: dict, swap_xy: bool) -> str:
    source, sink = inst["source"], inst["sink"]
    removed = {source, sink}
    adjacency = {v: [] for v in inst["nonterminals"]}
    near_source, near_sink = set(), set()
    for u, v in inst["edges"]:
        if u == source and v not in removed:
            near_source.add(v)
        elif v == source and u not in removed:
            near_source.add(u)
        if u == sink and v not in removed:
            near_sink.add(v)
        elif v == sink and u not in removed:
            near_sink.add(u)
        if u not in removed and v not in removed:
            adjacency.setdefault(u, []).append(v)
            adjacency.setdefault(v, []).append(u)

    xset, yset = set(inst["X"]), set(inst["Y"])
    if swap_xy:
        xset, yset = yset, xset
    colors = {
        v: (int(v == inst["marked"]), int(v in xset), int(v in yset),
            int(v in near_source), int(v in near_sink))
        for v in inst["nonterminals"]
    }
    unseen = set(inst["nonterminals"])
    parts = []
    while unseen:
        start = next(iter(unseen))
        stack = [start]
        component = {start}
        unseen.remove(start)
        while stack:
            u = stack.pop()
            for v in adjacency.get(u, ()):
                if v in unseen:
                    unseen.remove(v)
                    component.add(v)
                    stack.append(v)
        parts.append(_tree_component_digest(component, adjacency, colors))
    parts.sort()
    head = json.dumps({"k": inst["required_size"], "parts": len(parts)},
                      sort_keys=True).encode()
    return hashlib.sha256(head + b"".join(parts)).hexdigest()


def canonical_key(inst: dict) -> str:
    """Canonical colored-tree-forest key, independent of all vertex labels."""
    return min(_canonical_orientation(inst, False),
               _canonical_orientation(inst, True))


def escalate(params: dict):
    """Double the implicit forest and increase subdivision crowding at fixed k."""
    harder = dict(params)
    harder.pop("_preset", None)
    harder["n"] = int(params["n"]) + 1
    harder["q"] = int(params.get("q", 5)) + 1
    # r and depth, hence the answer length, deliberately remain fixed.
    return harder


