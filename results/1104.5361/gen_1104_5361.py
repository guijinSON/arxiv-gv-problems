def _coprime_multiplier(rng: random.Random, modulus: int) -> int:
    """Choose a nontrivial unit modulo modulus without global randomness."""
    while True:
        value = rng.randrange(2, modulus - 1)
        if math.gcd(value, modulus) == 1:
            return value


def _edge_length(j: int, ell_a: int, ell_b: int, ell_mod: int, q: int) -> int:
    return 1 + ((ell_a * j + ell_b) % ell_mod) % q


def make_instance(n: int, seed: int = 0, **params) -> dict:
    """Construct a promised X--Y separator instance and its frontier witness.

    ``n`` is the height of every complete binary tree.  Randomness changes the
    affine vertex relabelling, the marked root-to-leaf branch, and every edge's
    subdivision length.  The separator is composed directly from the marked
    branch's off-path siblings and the roots of the other trees.
    """
    height = int(n)
    r = int(params.get("r", 4))
    depth = int(params.get("depth", min(6, height)))
    q = int(params.get("q", 5))
    if height < 1 or r < 2 or q < 1 or not (1 <= depth <= height):
        raise ValueError("require n>=1, r>=2, q>=1, and 1<=depth<=n")

    rng = random.Random(seed)
    tree_size = (1 << (height + 1)) - 1
    base_count = r * tree_size
    a = _coprime_multiplier(rng, base_count)
    b = rng.randrange(base_count)
    a_inv = pow(a, -1, base_count)
    ell_mod = 2 * base_count + 1
    ell_a = rng.randrange(1, ell_mod)
    ell_b = rng.randrange(ell_mod)

    def enc(j: int) -> int:
        return (a * j + b) % base_count

    def branch(j: int) -> int:
        return q * enc(j)

    source, sink = -1, -2
    nonterminals = []
    edges = []

    for tree in range(r):
        offset = tree * tree_size
        root = offset
        nonterminals.append(branch(root))
        edges.append([source, branch(root)])
        for local in range(1, tree_size):
            j = offset + local
            parent = offset + (local - 1) // 2
            length = _edge_length(j, ell_a, ell_b, ell_mod, q)
            chain = [branch(parent)]
            for pos in range(length - 1, 0, -1):
                label = q * enc(j) + pos
                nonterminals.append(label)
                chain.append(label)
            nonterminals.append(branch(j))
            chain.append(branch(j))
            edges.extend([[chain[i], chain[i + 1]] for i in range(len(chain) - 1)])
        first_leaf = (1 << height) - 1
        for local in range(first_leaf, tree_size):
            edges.append([branch(offset + local), sink])

    marked_tree = rng.randrange(r)
    marked_local = (1 << depth) - 1 + rng.randrange(1 << depth)
    marked_j = marked_tree * tree_size + marked_local
    marked = branch(marked_j)

    # X protects the strict marked-path ancestors.  Consequently every off-path
    # sibling branch needs its own separator vertex, and the marked vertex itself
    # is needed for the remaining branch.
    ancestors_local = []
    cursor = marked_local
    while cursor:
        cursor = (cursor - 1) // 2
        ancestors_local.append(cursor)
    ancestors_local.reverse()
    x_vertices = [source] + [branch(marked_tree * tree_size + u)
                             for u in ancestors_local]

    answer = [marked]
    for tree in range(r):
        if tree != marked_tree:
            answer.append(branch(tree * tree_size))
    cursor = marked_local
    for _ in range(depth):
        sibling = cursor + 1 if cursor % 2 == 1 else cursor - 1
        answer.append(branch(marked_tree * tree_size + sibling))
        cursor = (cursor - 1) // 2
    answer.sort()

    # All lists are deterministic; sorting vertices also makes attack tie-breaking
    # independent of construction order.
    nonterminals = sorted(set(nonterminals))
    allowed_vertices = [v for v in nonterminals if v not in set(x_vertices)]
    inst = {
        "n": height,
        "r": r,
        "depth": depth,
        "q": q,
        "tree_size": tree_size,
        "base_count": base_count,
        "a": a,
        "b": b,
        "a_inv": a_inv,
        "ell_a": ell_a,
        "ell_b": ell_b,
        "ell_mod": ell_mod,
        "source": source,
        "sink": sink,
        "X": sorted(x_vertices),
        "Y": [sink],
        "marked": marked,
        "required_size": r + depth,
        "nonterminals": nonterminals,
        "allowed_vertices": allowed_vertices,
        "candidate_pool": [v for v in allowed_vertices if v != marked],
        "edges": edges,
        "answer": answer,
    }
    return inst


