def parse_answer(text: str) -> object | None:
    if not isinstance(text, str):
        return None
    blocks = re.findall(r"<answer\b[^>]*>(.*?)</answer>", text,
                        flags=re.IGNORECASE | re.DOTALL)
    candidates = list(reversed(blocks))
    if not candidates:
        fenced = re.findall(r"```(?:json)?\s*(\[[\s\S]*?\])\s*```", text,
                            flags=re.IGNORECASE)
        candidates.extend(reversed(fenced))
    for raw in candidates:
        try:
            value = json.loads(raw.strip())
        except (TypeError, ValueError):
            continue
        if (isinstance(value, list)
                and all(isinstance(x, int) and not isinstance(x, bool)
                        for x in value)):
            return value
    return None


def verify(inst: dict, answer: object) -> tuple[bool, str]:
    n = inst["n"]
    q = inst["q"]
    if not isinstance(answer, list):
        return False, "answer must be a JSON list"
    if not answer:
        return False, "answer list is empty"
    if len(answer) != n:
        return False, f"expected exactly {n} exponents, got {len(answer)}"
    for i, x in enumerate(answer):
        if isinstance(x, bool) or not isinstance(x, int):
            return False, f"entry {i} is not an integer"
        if not 0 <= x < q:
            return False, f"entry {i}={x} is outside the inclusive range 0..{q-1}"

    matrix = inst["base_log_matrix"]
    target = inst["target_logs"]
    for j, (row, expected) in enumerate(zip(matrix, target)):
        actual = sum(a * x for a, x in zip(row, answer)) % q
        if actual != expected:
            return False, (
                f"coordinate {j} mismatch: product log is {actual}, "
                f"target log is {expected}"
            )

    for j, (p, h, expected_residue) in enumerate(zip(
            inst["prime_factors"], inst["coordinate_roots"],
            inst["target_residues"])):
        exponent = sum(matrix[j][i] * answer[i] for i in range(n)) % q
        residue = pow(h, exponent, p)
        if residue != expected_residue:
            return False, (
                f"CRT residue {j} mismatch: product is {residue}, "
                f"target is {expected_residue}"
            )
    return True, "ok"


