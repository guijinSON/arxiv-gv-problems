    answer = inst["answer"]
    if not _is_prime(q):
        errors.append("q is not prime")
    if len(set(primes)) != n or any(not _is_prime(p) for p in primes):
        errors.append("CRT factors are not distinct primes")
    if any(h == 1 or pow(h, q, p) != 1
           for p, h in zip(primes, roots)):
        errors.append("a coordinate root does not have exact order q")
    if len(matrix) != n or any(len(row) != n for row in matrix):
        errors.append("base-log matrix has the wrong shape")
        return errors
    v = [(matrix[0][i] - (1 if i == 0 else 0)) % q for i in range(n)]
    expected = [
        [(v[i] + (1 if i == j else 0)) % q for i in range(n)]
        for j in range(n)
    ]
    if matrix != expected or (1 + sum(v)) % q == 0:
        errors.append("base-log matrix is not an invertible I + 1 v^T")
    if len(set(answer)) == 1:
        errors.append("Theorem 1 unequal-exponent condition is absent")
    if not _avoids_easy_projections(matrix, answer, q):
        errors.append("a Theorem 2 one-coordinate projection is present")
    if _full_product_logs(matrix, answer, q) != inst["target_logs"]:
        errors.append("target logs do not equal A*k")
    if any(pow(h, y, p) != residue for p, h, y, residue in zip(
            primes, roots, inst["target_logs"], inst["target_residues"])):
        errors.append("target CRT residue disagrees with its exact log")
    return errors


