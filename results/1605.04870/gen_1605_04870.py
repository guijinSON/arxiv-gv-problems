def _rebase_coordinates(inst: dict, scales: list[int]) -> tuple[dict, list[int]]:
    """Change each displayed order-q coordinate root without changing g_i/beta."""
    n = inst["n"]
    q = inst["q"]
    if len(scales) != n or any(not 1 <= u < q for u in scales):
        raise ValueError("each coordinate scale must be nonzero in F_q")
    inverses = [pow(u, -1, q) for u in scales]
    moved = {
        "n": n,
        "q": q,
        "cofactor_start": inst["cofactor_start"],
        "modulus_N": inst["modulus_N"],
        "prime_factors": list(inst["prime_factors"]),
        "coordinate_roots": [
            pow(h, u, p) for h, u, p in zip(
                inst["coordinate_roots"], scales, inst["prime_factors"])
        ],
        "base_log_matrix": [
            [(z * inverses[r]) % q for z in row]
            for r, row in enumerate(inst["base_log_matrix"])
        ],
        "target_logs": [
            (z * inverses[r]) % q for r, z in enumerate(inst["target_logs"])
        ],
        "target_residues": list(inst["target_residues"]),
        "answer": list(inst["answer"]),
        "_fast_rank_one": False,
    }
    return moved, list(moved["answer"])


def escalate(params: dict) -> dict | str | None:
    """Increase field/modulus size while keeping the exponent tuple length fixed."""
    n = int(params["n"])
    q = int(params["q"])
    cofactor_start = int(params.get("cofactor_start", 8000))
    new_q = _next_prime(4 * q + 1)
    new_cofactor = 2 * cofactor_start
    worst_chars = 2 + n * (len(str(new_q - 1)) + 2)
    if worst_chars > 1900 or new_q * (4 * new_cofactor + 100000) >= 2**64:
        return "cap_bound"
    harder = dict(params)
    harder["q"] = new_q
    harder["cofactor_start"] = new_cofactor
    return harder


def _reference_gauss(inst: dict) -> dict:
    q = inst["q"]
    n = inst["n"]
    aug = [list(row) + [rhs] for row, rhs in zip(
        inst["base_log_matrix"], inst["target_logs"])]
    operations = 0
    t0 = time.perf_counter()
    for col in range(n):
        pivot = next((r for r in range(col, n) if aug[r][col] % q), None)
        if pivot is None:
            return {"ok": False, "answer": None,
                    "operations": operations,
                    "wall_clock_sec": time.perf_counter() - t0}
        if pivot != col:
            aug[col], aug[pivot] = aug[pivot], aug[col]
        inv = pow(aug[col][col], -1, q)
        operations += 1
        for j in range(col, n + 1):
            aug[col][j] = aug[col][j] * inv % q
            operations += 1
        for r in range(n):
            if r == col or aug[r][col] % q == 0:
                continue
            factor = aug[r][col]
            for j in range(col, n + 1):
                aug[r][j] = (aug[r][j] - factor * aug[col][j]) % q
                operations += 2
    answer = [aug[i][n] % q for i in range(n)]
    elapsed = time.perf_counter() - t0
    return {
        "ok": verify(inst, answer)[0],
        "answer": answer,
        "operations": operations,
        "wall_clock_sec": elapsed,
    }


def _attack_target(inst: dict) -> list[int]:
    return list(inst["target_logs"])


def _attack_column_outlier(inst: dict) -> list[int]:
    """Use each column's repeated-value statistic as a direct correction."""
    matrix = inst["base_log_matrix"]
    q = inst["q"]
    n = inst["n"]
    modes = []
    for c in range(n):
        counts: dict[int, int] = {}
        for r in range(n):
            z = matrix[r][c]
            counts[z] = counts.get(z, 0) + 1
        modes.append(max(counts.items(), key=lambda item: item[1])[0])
    return [(inst["target_logs"][i] - modes[i]) % q for i in range(n)]


def _attack_diagonal(inst: dict) -> list[int]:
    return _attack_diagonal_data(
        inst["base_log_matrix"], inst["target_logs"], inst["q"])


def _attack_greedy(inst: dict) -> list[int]:
    return _attack_greedy_data(
        inst["base_log_matrix"], inst["target_logs"], inst["q"])


def _attack_average(inst: dict) -> list[int]:
    q = inst["q"]
    c = sum(inst["target_logs"]) * pow(inst["n"], -1, q) % q
    return [(z - c) % q for z in inst["target_logs"]]


def _attack_random_scalar(inst: dict) -> tuple[bool, int]:
    tries = _random_shift_values(inst["target_logs"], inst["q"])
    for c in tries:
        candidate = [(z - c) % inst["q"] for z in inst["target_logs"]]
        if verify(inst, candidate)[0]:
            return True, len(tries) * inst["n"]
    return False, len(tries) * inst["n"]


