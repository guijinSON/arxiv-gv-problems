def parse_answer(text: str) -> object | None:
    if not isinstance(text, str):
        return None
    match = _ANSWER_RE.search(text)
    payload = match.group(1).strip() if match else text.strip()
    payload = re.sub(r"^```(?:json)?\s*", "", payload, flags=re.I)
    payload = re.sub(r"\s*```$", "", payload)
    try:
        value = json.loads(payload)
    except (TypeError, ValueError):
        decoder = json.JSONDecoder()
        for start, char in enumerate(payload):
            if char != "[":
                continue
            try:
                value, _end = decoder.raw_decode(payload[start:])
                break
            except ValueError:
                continue
        else:
            return None
    if not isinstance(value, list):
        return None
    return value


def _answer_shape_reason(answer: object, p: int) -> str | None:
    if not isinstance(answer, list):
        return "answer must be a JSON 2 by 2 matrix"
    if len(answer) != 2:
        return f"answer matrix must have 2 rows, got {len(answer)}"
    for i, row in enumerate(answer):
        if not isinstance(row, list) or len(row) != 2:
            got = len(row) if isinstance(row, list) else "non-list"
            return f"row {i} must have 2 entries, got {got}"
        for j, entry in enumerate(row):
            if isinstance(entry, bool) or not isinstance(entry, int):
                return f"entry ({i},{j}) must be an integer"
            if not 0 <= entry < p:
                return f"entry ({i},{j}) is outside 0..{p - 1}"
    flat = [entry for row in answer for entry in row]
    first = next((entry for entry in flat if entry), None)
    if first != 1:
        return "projective matrix is not normalized: first nonzero entry must be 1"
    if _det(answer, p) == 0:
        return "projective matrix must be invertible"
    return None


def verify(inst: dict, answer: object) -> tuple[bool, str]:
    """Check any normalized projective graph isomorphism; never read the plant."""
    p = inst["p"]
    reason = _answer_shape_reason(answer, p)
    if reason is not None:
        return False, reason
    T = answer  # type: ignore[assignment]
    try:
        transported = _conjugate(T, inst["generator_a"], p)
        forward = _normalize(inst["generator_b"], p)
        backward = _normalize(_mat_inv(inst["generator_b"], p), p)
    except (ValueError, ZeroDivisionError):
        return False, "projective matrix arithmetic failed"
    if transported not in (forward, backward):
        return False, "matrix does not preserve the projective cycle edges"
    return True, "ok"


def random_candidate(inst: dict, rng: random.Random) -> object:
    """Uniformly sample projectivities obeying the obvious hub constraint."""
    return _random_hub_mapping_projectivity(inst, rng)


def search_space(inst: dict) -> int:
    p = inst["p"]
    return p * (p - 1)  # one point-stabilizer coset in PGL(2,p)


def _all_normalized_pgl(p: int):
    for a in range(p):
        for b in range(p):
            for c in range(p):
                for d in range(p):
                    matrix = [[a, b], [c, d]]
                    if _det(matrix, p) and _normalize(matrix, p) == matrix:
                        yield matrix


def enumerate_all(inst: dict) -> int | None:
    if inst["p"] ** 4 > _ENUMERATION_CAP:
        return None
    return sum(1 for candidate in _all_normalized_pgl(inst["p"])
               if verify(inst, candidate)[0])


def canonical_key(inst: dict) -> str:
    """Complete graph-pair invariant for this constructed family."""
    # Each side is exactly a p-wheel with q pendant leaves at its hub. Generator
    # conjugation, reversal, side swapping, and arbitrary vertex relabelling do
    # not change these three structural numbers.
    invariant = [inst["p"], inst["pendant_count"], inst["tree_width"]]
    blob = json.dumps(invariant, separators=(",", ":"))
    return hashlib.sha256(blob.encode("ascii")).hexdigest()


