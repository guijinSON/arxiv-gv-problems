def _is_power_of_two(n: int) -> bool:
    return isinstance(n, int) and not isinstance(n, bool) and n >= 4 and not (n & (n - 1))


def _parity(value: int) -> int:
    return value.bit_count() & 1


def _bitstring(value: int, width: int) -> str:
    """Coordinates 0..width-1, left to right (little-endian by coordinate)."""
    return "".join("1" if (value >> i) & 1 else "0" for i in range(width))


def _word_value(word: str) -> int:
    value = 0
    for i, char in enumerate(word):
        if char == "1":
            value |= 1 << i
    return value


def _apply_binary_matrix(rows: list[int], value: int) -> int:
    result = 0
    for i, row in enumerate(rows):
        result |= _parity(row & value) << i
    return result


def _random_invertible_matrix(width: int, rng: random.Random) -> list[int]:
    rows = [1 << i for i in range(width)]
    for _ in range(max(12, 8 * width)):
        i = rng.randrange(width)
        j = rng.randrange(width - 1)
        if j >= i:
            j += 1
        if rng.randrange(3) == 0:
            rows[i], rows[j] = rows[j], rows[i]
        else:
            rows[i] ^= rows[j]
    return rows


def _random_word(length: int, alphabet: tuple[str, ...], rng: random.Random) -> tuple[str, ...]:
    return tuple(alphabet[rng.randrange(len(alphabet))] for _ in range(length))


def _hex_from_signs(signs: list[int]) -> str:
    bits = "".join("0" if sign == 1 else "1" for sign in signs)
    return format(int(bits, 2), f"0{len(bits) // 4}x")


def _signs_from_hex(blob: str, n: int) -> list[int]:
    bits = format(int(blob, 16), f"0{n}b")
    return [1 if bit == "0" else -1 for bit in bits]


def _column_index(inst: dict, kind: str, label: str | None = None) -> int | None:
    for index, monomial in enumerate(inst["monomials"]):
        if monomial["kind"] == kind and (label is None or monomial.get("label") == label):
            return index
    return None


def _rows_in_label_order(inst: dict) -> list[dict]:
    return sorted(inst["generators"], key=lambda row: _word_value(row["label"]))


def make_instance(
    n: int,
    seed: int = 0,
    coefficient_bits: int = 16,
    padding: int = 2,
    **params,
) -> dict:
    """Inverse-generate a homogeneous free-algebra membership witness."""
    if params:
        raise TypeError("unknown parameters: " + ", ".join(sorted(params)))
    if not _is_power_of_two(n):
        raise ValueError("n must be a power of two and at least 4")
    if not isinstance(coefficient_bits, int) or isinstance(coefficient_bits, bool) or not (2 <= coefficient_bits <= 256):
        raise ValueError("coefficient_bits must be an integer from 2 through 256")
    if not isinstance(padding, int) or isinstance(padding, bool) or not (0 <= padding <= 64):
        raise ValueError("padding must be an integer from 0 through 64")

    width = n.bit_length() - 1
    rng = random.Random(seed)
    shuffled_tokens = list(_TOKENS)
    rng.shuffle(shuffled_tokens)
    left_token, right_token, zero_token, one_token = shuffled_tokens
    alphabet = tuple(shuffled_tokens)

    # Choose the answer before any public generator.  The exclusions make the
    # named cheap attacks genuine negatives; they do not solve an instance.
    while True:
        affine_rows = _random_invertible_matrix(width, rng)
        offset = rng.randrange(n)
        secret = rng.randrange(1, n - 1)
        secret_word = _bitstring(secret, width)
        target_character = _apply_binary_matrix(affine_rows, secret) ^ offset
        if (
            secret_word != secret_word[::-1]
            and target_character != 0
            and _apply_binary_matrix(affine_rows, secret) != secret
        ):
            break

    prefix = [left_token] + [alphabet[rng.randrange(4)] for _ in range(padding)]
    suffix = [alphabet[rng.randrange(4)] for _ in range(padding)] + [right_token]
    word_length = len(prefix) + width + len(suffix)
    candidate_words = []
    used: set[tuple[str, ...]] = set()
    for value in range(n):
        bits = _bitstring(value, width)
        middle = [one_token if bit == "1" else zero_token for bit in bits]
        word = tuple(prefix + middle + suffix)
        candidate_words.append(word)
        used.add(word)

    auxiliary_words = []
    while len(auxiliary_words) < n:
        word = _random_word(word_length, alphabet, rng)
        if word not in used:
            used.add(word)
            auxiliary_words.append(word)

    monomials = []
    for value in range(n):
        label = _bitstring(value, width)
        monomials.append({
            "word": list(candidate_words[value]),
            "kind": "candidate",
            "label": label,
        })
        monomials.append({
            "word": list(auxiliary_words[value]),
            "kind": "auxiliary",
            "label": label,
        })
    column_order = list(range(2 * n))
    rng.shuffle(column_order)
    monomials = [monomials[index] for index in column_order]

    minimum = 1 << (coefficient_bits - 1)
    maximum = (1 << coefficient_bits) - 1
    rows = []
    for z in range(n):
        scale = rng.randrange(minimum, maximum + 1)
        if scale % 2 == 0:
            scale = scale + 1 if scale < maximum else scale - 1
        natural_signs = []
        for value in range(n):
            character = _apply_binary_matrix(affine_rows, value) ^ offset
            sign = -1 if _parity(z & character) else 1
            natural_signs.extend((sign, -sign))
        signs = [natural_signs[index] for index in column_order]
        rows.append({
            "label": _bitstring(z, width),
            "scale": scale,
            "signs": "".join("+" if sign == 1 else "-" for sign in signs),
        })
    rng.shuffle(rows)

    certificate_signs = [
        -1 if _parity(z & target_character) else 1 for z in range(n)
    ]
    answer = {
        "x": secret_word,
        "signs_hex": _hex_from_signs(certificate_signs),
    }
    c_word = list(auxiliary_words[secret])
    return {
        "family": "homogeneous noncommutative ideal element",
        "field": "Q",
        "n": n,
        "bit_width": width,
        "coefficient_bits": coefficient_bits,
        "padding": padding,
        "variables": list(alphabet),
        "bit_tokens": {"0": zero_token, "1": one_token},
        "prefix": prefix,
        "suffix": suffix,
        "word_length": word_length,
        "target_c": c_word,
        "monomials": monomials,
        "generators": rows,
        "answer": answer,
    }


def _word_text(word: list[str] | tuple[str, ...]) -> str:
    return " ".join(word)


