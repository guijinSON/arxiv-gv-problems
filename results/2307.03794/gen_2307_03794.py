def _hopcroft_karp_reference(inst):
    """Paper-standard maximum matching with exact operation counters."""
    n = inst["n"]
    adjacency = inst["better_preferences"]
    pair_agent = [-1] * n
    pair_house = [-1] * n
    distance = [0] * n
    counts = {
        "edge_scans": 0,
        "bfs_rounds": 0,
        "dfs_calls": 0,
        "augmentations": 0,
    }

    def bfs():
        counts["bfs_rounds"] += 1
        queue = deque()
        found = False
        for agent in range(n):
            if pair_agent[agent] < 0:
                distance[agent] = 0
                queue.append(agent)
            else:
                distance[agent] = -1
        while queue:
            agent = queue.popleft()
            for house in adjacency[agent]:
                counts["edge_scans"] += 1
                other = pair_house[house]
                if other < 0:
                    found = True
                elif distance[other] < 0:
                    distance[other] = distance[agent] + 1
                    queue.append(other)
        return found

    def dfs(agent):
        counts["dfs_calls"] += 1
        for house in adjacency[agent]:
            counts["edge_scans"] += 1
            other = pair_house[house]
            if other < 0 or (
                distance[other] == distance[agent] + 1 and dfs(other)
            ):
                pair_agent[agent] = house
                pair_house[house] = agent
                return True
        distance[agent] = -1
        return False

    while bfs():
        progress = False
        for agent in range(n):
            if pair_agent[agent] < 0 and dfs(agent):
                counts["augmentations"] += 1
                progress = True
        if not progress:
            break
    if any(house < 0 for house in pair_agent):
        return None, counts
    return pair_agent, counts


def _compact_conserved_sum(inst):
    """Recover one whole matching layer from the first displayed improving edge."""
    q = inst["modulus"]
    first_house = inst["better_preferences"][0][0]
    constant = (
        inst["agent_scalars"][0] + inst["house_scalars"][first_house]
    ) % q
    scalar_to_house = {
        scalar: code for code, scalar in enumerate(inst["house_scalars"])
    }
    answer = []
    for scalar in inst["agent_scalars"]:
        target = (constant - scalar) % q
        code = scalar_to_house.get(target, -1)
        answer.append(code)
    return answer, inst["n"] + 1


def _attack_row_extreme(inst, largest=False):
    return [
        (max(row) if largest else min(row))
        for row in inst["better_preferences"]
    ]


def _attack_first_listed(inst):
    return [row[0] for row in inst["better_preferences"]]


def _attack_scalar_nearest(inst):
    q = inst["modulus"]
    answer = []
    for scalar, row in zip(inst["agent_scalars"], inst["better_preferences"]):
        answer.append(min(
            row,
            key=lambda code: (
                min(
                    (inst["house_scalars"][code] - scalar) % q,
                    (scalar - inst["house_scalars"][code]) % q,
                ),
                code,
            ),
        ))
    return answer


def _attack_constant_difference(inst):
    """Try the obvious but wrong modular ansatz y-x=d."""
    n = inst["n"]
    scale = inst["scale"]
    agent_offset = inst["agent_scalars"][0] % scale
    house_offset = inst["house_scalars"][0] % scale
    agent_coordinates = [
        (scalar - agent_offset) // scale for scalar in inst["agent_scalars"]
    ]
    house_coordinates = [
        (scalar - house_offset) // scale for scalar in inst["house_scalars"]
    ]
    coordinate_to_house = {
        coordinate: code for code, coordinate in enumerate(house_coordinates)
    }
    first_i = agent_coordinates[0]
    differences = [
        (house_coordinates[code] - first_i) % n
        for code in inst["better_preferences"][0]
    ]

    def support(difference):
        return sum(
            coordinate_to_house[(i + difference) % n] in row
            for i, row in zip(agent_coordinates, inst["better_preferences"])
        )

    best = max(differences, key=lambda value: (support(value), -value))
    answer = []
    for i, row in zip(agent_coordinates, inst["better_preferences"]):
        proposed = coordinate_to_house[(i + best) % n]
        answer.append(proposed if proposed in row else row[0])
    return answer


def _attack_greedy(inst, rng=None, attempts=1):
    """Assign an unused preferred house row by row, without augmenting paths."""
    n = inst["n"]
    last = _attack_first_listed(inst)
    for _ in range(attempts):
        order = list(range(n))
        if rng is not None:
            rng.shuffle(order)
        used = set()
        answer = [None] * n
        for agent in order:
            choices = [
                house for house in inst["better_preferences"][agent]
                if house not in used
            ]
            if not choices:
                break
            house = rng.choice(choices) if rng is not None else choices[0]
            answer[agent] = house
            used.add(house)
        else:
            if verify(inst, answer)[0]:
                return answer, True
        last = [
            answer[i] if answer[i] is not None else inst["better_preferences"][i][0]
            for i in range(n)
        ]
    return last, False


def _transform_instance(
    inst,
    agent_map=None,
    house_map=None,
    row_orders=None,
    catalog_order=None,
):
    """Apply arbitrary code and presentation relabellings, carrying the witness."""
    n = inst["n"]
    agent_map = list(range(n)) if agent_map is None else list(agent_map)
    house_map = list(range(n)) if house_map is None else list(house_map)
    if row_orders is None:
        row_orders = [list(range(len(row))) for row in inst["better_preferences"]]

    agent_scalars = [None] * n
    rows = [None] * n
    answer = [None] * n
    house_scalars = [None] * n
    for old_house, new_house in enumerate(house_map):
        house_scalars[new_house] = inst["house_scalars"][old_house]
    for old_agent, new_agent in enumerate(agent_map):
        agent_scalars[new_agent] = inst["agent_scalars"][old_agent]
        old_row = inst["better_preferences"][old_agent]
        rows[new_agent] = [house_map[old_row[j]] for j in row_orders[old_agent]]
        answer[new_agent] = house_map[inst["answer"][old_agent]]
    mapped_catalog = [house_map[code] for code in inst["house_order"]]
    if catalog_order is not None:
        mapped_catalog = [mapped_catalog[j] for j in catalog_order]
    return {
        "n": n,
        "k": n,
        "modulus": inst["modulus"],
        "scale": inst["scale"],
        "agent_scalars": agent_scalars,
        "house_scalars": house_scalars,
        "house_order": mapped_catalog,
        "better_preferences": rows,
        "current_matching": [f"C{i}" for i in range(n)],
        "answer": answer,
    }


def _affine_coordinate_transform(inst, unit, agent_translation, house_translation):
    """Apply i->ui+t_A and j->uj+t_B in Z_n; codes and witness stay fixed."""
    n = inst["n"]
    if math.gcd(unit, n) != 1:
        raise ValueError("unit must be invertible modulo n")
    scale = inst["scale"]
    agent_offset = inst["agent_scalars"][0] % scale
    house_offset = inst["house_scalars"][0] % scale
    agent_scalars = []
    for scalar in inst["agent_scalars"]:
        coordinate = (scalar - agent_offset) // scale
        transformed = (unit * coordinate + agent_translation) % n
        agent_scalars.append(agent_offset + transformed * scale)
    house_scalars = []
    for scalar in inst["house_scalars"]:
        coordinate = (scalar - house_offset) // scale
        transformed = (unit * coordinate + house_translation) % n
        house_scalars.append(house_offset + transformed * scale)
    transformed = dict(inst)
    transformed["agent_scalars"] = agent_scalars
    transformed["house_scalars"] = house_scalars
    transformed["answer"] = list(inst["answer"])
    return transformed


