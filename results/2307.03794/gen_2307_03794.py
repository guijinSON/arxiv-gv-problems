def _normalised_shift_set(inst):
    """Recover the cyclic layer set from instance data, never from the answer."""
    n = inst["n"]
    scale = inst["scale"]
    agent_offset = inst["agent_scalars"][0] % scale
    house_offset = inst["house_scalars"][0] % scale
    expected = None
    for scalar, row in zip(inst["agent_scalars"], inst["better_preferences"]):
        i = (scalar - agent_offset) // scale
        shifts = tuple(sorted(
            (i + (inst["house_scalars"][code] - house_offset) // scale) % n
            for code in row
        ))
        if expected is None:
            expected = shifts
        elif shifts != expected:
            raise ValueError("instance is not a union of common cyclic layers")
    return expected or ()


def canonical_key(inst):
    """Canonicalize the layer set under affine coordinate relabellings of Z_n.

    Agent codes, house codes, catalog order, preference order, coordinate
    translations, and simultaneous multiplication by a unit are all removed.
    """
    n = inst["n"]
    shifts = _normalised_shift_set(inst)
    best = None
    for unit in range(n):
        if math.gcd(unit, n) != 1:
            continue
        multiplied = [(unit * shift) % n for shift in shifts]
        for translation in range(n):
            candidate = tuple(sorted((value + translation) % n for value in multiplied))
            if best is None or candidate < best:
                best = candidate
    payload = [n, list(best or ())]
    blob = json.dumps(payload, separators=(",", ":"))
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


