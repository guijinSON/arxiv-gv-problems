def _is_int(value):
    return isinstance(value, int) and not isinstance(value, bool)


def _validate_params(n, seed, layer_count, scale):
    if not _is_int(n) or n < 3:
        raise ValueError("n must be an integer at least 3")
    if not _is_int(seed):
        raise ValueError("seed must be an integer")
    if not _is_int(layer_count) or not 2 <= layer_count < n:
        raise ValueError("layer_count must be an integer with 2 <= layer_count < n")
    if not _is_int(scale) or scale < 1:
        raise ValueError("scale must be a positive integer")


def make_instance(n, seed=0, layer_count=4, scale=101, **params):
    """Compose equal-distribution cyclic matching layers before shuffling names.

    Let agent and house coordinates be i,j in Z_n.  A sampled layer s contains
    every edge i--j with i+j=s mod n, hence it is a perfect matching.  All
    layers use the same construction; choosing the first sampled layer as the
    retained certificate does not make its edges locally distinguishable.
    """
    _validate_params(n, seed, layer_count, scale)
    rng = random.Random(seed)
    modulus = n * scale
    agent_offset = rng.randrange(scale)
    house_offset = rng.randrange(scale)

    # Random house codes B0,...,B(n-1) conceal the cyclic coordinate order.
    raw_house_scalars = [house_offset + j * scale for j in range(n)]
    rng.shuffle(raw_house_scalars)
    house_scalars = raw_house_scalars
    scalar_to_house = {scalar: code for code, scalar in enumerate(house_scalars)}
    house_order = list(range(n))
    rng.shuffle(house_order)

    agent_scalars = [agent_offset + i * scale for i in range(n)]
    rng.shuffle(agent_scalars)
    shifts = rng.sample(range(n), layer_count)
    planted_shift = shifts[0]
    planted_constant = (
        agent_offset + house_offset + planted_shift * scale
    ) % modulus

    better_preferences = []
    answer = []
    for scalar in agent_scalars:
        row = []
        for shift in shifts:
            conserved = (agent_offset + house_offset + shift * scale) % modulus
            target_scalar = (conserved - scalar) % modulus
            row.append(scalar_to_house[target_scalar])
        rng.shuffle(row)
        better_preferences.append(row)
        answer.append(scalar_to_house[(planted_constant - scalar) % modulus])

    return {
        "n": n,
        "k": n,
        "modulus": modulus,
        "scale": scale,
        "agent_scalars": agent_scalars,
        "house_scalars": house_scalars,
        "house_order": house_order,
        "better_preferences": better_preferences,
        "current_matching": [f"C{i}" for i in range(n)],
        "answer": answer,
    }


