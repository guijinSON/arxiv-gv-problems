def parse_answer(text):
    """Extract the last delimited integer list, tolerating prose and fences."""
    if not isinstance(text, str):
        return None
    blocks = _ANSWER_RE.findall(text)
    if not blocks:
        return None
    body = blocks[-1].strip()
    if body.startswith("[") and body.endswith("]"):
        body = body[1:-1].strip()
    if not body:
        return []
    if not re.fullmatch(r"(?:B\s*)?[+-]?\d+(?:\s*,\s*(?:B\s*)?[+-]?\d+)*", body, re.I):
        return None
    try:
        return [int(re.sub(r"^[Bb]\s*", "", token.strip())) for token in body.split(",")]
    except (TypeError, ValueError):
        return None


def verify(inst, answer):
    """Check the proposed Pareto-improving matching exactly, without the plant."""
    if not isinstance(answer, list):
        return False, "answer must be a list of better-house codes"
    n = inst["n"]
    if not answer:
        return False, "answer is empty"
    if len(answer) < n:
        return False, f"too few assignments: expected {n}, got {len(answer)}"
    if len(answer) > n:
        return False, f"too many assignments: expected {n}, got {len(answer)}"
    for i, code in enumerate(answer):
        if not _is_int(code) or not 0 <= code < n:
            return False, f"entry {i} is not a displayed better-house code"
    if len(set(answer)) != n:
        return False, "matching constraint is violated by a repeated house"
    for agent, code in enumerate(answer):
        if code not in inst["better_preferences"][agent]:
            return False, f"agent A{agent} does not prefer house B{code} to its current object"
    return True, "ok"


