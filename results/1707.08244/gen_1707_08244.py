def _is_int(value):
    return isinstance(value, int) and not isinstance(value, bool)


def _inv(value):
    value %= _P
    if value == 0:
        raise ValueError("zero has no inverse modulo 1019")
    return pow(value, _P - 2, _P)


def _validate(n, m, k):
    for name, value in (("n", n), ("m", m), ("k", k)):
        if not _is_int(value):
            raise ValueError(f"{name} must be an integer")
    if not 3 <= n <= _P:
        raise ValueError("n must lie in 3..1019")
    if not 3 <= k <= min(n, 119) or k % 2 == 0:
        raise ValueError("k must be odd and lie in 3..min(n,119)")
    if not k + 1 <= m <= min(n, _P - 1):
        raise ValueError("m must lie in k+1..min(n,1018)")


def _generators(labels, exponents):
    return [[pow(label, exponent, _P) for exponent in exponents]
            for label in labels]


def _linear_combination(generators, coefficients, m):
    target = []
    for coordinate in range(m):
        total = 0
        for coefficient, generator in zip(coefficients, generators):
            total = (total + coefficient * generator[coordinate]) % _P
        target.append(total)
    return target


def make_instance(n, seed=0, **params):
    """Inverse-generate a native SMP instance and its exact group-term witness."""
    m = params.pop("m", None)
    k = params.pop("k", None)
    if params:
        raise TypeError("unknown parameters: " + ", ".join(sorted(params)))
    _validate(n, m, k)
    if not _is_int(seed):
        raise ValueError("seed must be an integer")

    rng = random.Random(seed)
    half = k // 2
    center = rng.randrange(_P)
    # Excluding +/-1 makes the explicit center-plus-consecutive in-context
    # heuristic a genuine failed attack.  Every planted label remains marginally
    # uniform because the independently uniform center translates the progression.
    steps = list(range(2, _P - 1))
    step = steps[rng.randrange(len(steps))]
    planted_labels = {
        (center + offset * step) % _P
        for offset in range(-half, half + 1)
    }
    if len(planted_labels) != k:
        raise AssertionError("arithmetic progression unexpectedly collided")

    remaining = [value for value in range(_P) if value not in planted_labels]
    decoys = rng.sample(remaining, n - k)
    labels = list(planted_labels) + decoys
    rng.shuffle(labels)

    exponents = list(range(m))
    generators = _generators(labels, exponents)
    coefficients = [int(label in planted_labels) for label in labels]
    target = _linear_combination(generators, coefficients, m)

    return {
        "modulus": _P,
        "n": n,
        "m": m,
        "exponents": exponents,
        "labels": labels,
        "generators": generators,
        "target": target,
        "answer": coefficients,
    }


