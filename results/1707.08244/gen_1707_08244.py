def parse_answer(text):
    """Extract the tagged JSON coefficient vector; return None on any garbage."""
    if not isinstance(text, str):
        return None
    match = _ANSWER_RE.search(text)
    if not match:
        return None
    payload = match.group(1).strip()
    fence = _FENCE_RE.fullmatch(payload)
    if fence:
        payload = fence.group(1).strip()
    try:
        answer = json.loads(payload)
    except (TypeError, ValueError, json.JSONDecodeError):
        return None
    if not isinstance(answer, list):
        return None
    if any(not _is_int(value) for value in answer):
        return None
    return answer


def verify(inst, answer):
    """Check any coefficient-term witness exactly, never consulting answer."""
    if not isinstance(answer, list):
        return False, "answer_not_a_list"
    if not answer:
        return False, "empty_answer"
    n = inst["n"]
    if len(answer) < n:
        return False, f"missing_coefficients_expected_{n}_got_{len(answer)}"
    if len(answer) > n:
        return False, f"extra_coefficients_expected_{n}_got_{len(answer)}"
    for index, coefficient in enumerate(answer):
        if not _is_int(coefficient):
            return False, f"coefficient_{index}_not_an_integer"
        if not 0 <= coefficient < _P:
            return False, f"coefficient_{index}_out_of_range"

    generators = inst["generators"]
    for coordinate, expected in enumerate(inst["target"]):
        actual = 0
        for index, coefficient in enumerate(answer):
            actual = (actual + coefficient * generators[index][coordinate]) % _P
        if actual != expected:
            exponent = inst["exponents"][coordinate]
            return False, (
                f"coordinate_{coordinate}_exponent_{exponent}_mismatch_"
                f"expected_{expected}_got_{actual}"
            )
    return True, "ok"


def random_candidate(inst, rng):
    """Sample uniformly after enforcing the freely visible exponent-zero sum."""
    if not isinstance(rng, random.Random):
        raise TypeError("rng must be an instance of random.Random")
    n = inst["n"]
    coefficients = [rng.randrange(_P) for _ in range(n - 1)]
    zero_coordinate = inst["exponents"].index(0)
    final = (inst["target"][zero_coordinate] - sum(coefficients)) % _P
    coefficients.append(final)
    return coefficients


def search_space(inst):
    """Size of the exponent-zero-conditioned coefficient language."""
    return _P ** (inst["n"] - 1)


def enumerate_all(inst):
    """Brute-force only when the declared space is genuinely tiny."""
    if search_space(inst) > 200_000:
        return None
    count = 0
    rng_values = range(_P)
    # This branch is unreachable for supported n, but keeps the function exact.
    if inst["n"] == 1:
        for value in rng_values:
            ok, _ = verify(inst, [value])
            count += int(ok)
        return count
    return None


def _power_sums_by_exponent(inst):
    return dict(zip(inst["exponents"], inst["target"]))


def _symmetry_candidate(inst):
    """The compact route: recover the centered odd progression from p1,p2."""
    sums = _power_sums_by_exponent(inst)
    if not all(exponent in sums for exponent in (0, 1, 2)):
        return None
    k = sums[0] % _P
    if not 3 <= k <= 119 or k % 2 == 0 or k > inst["n"]:
        return None
    half = k // 2
    center = sums[1] * _inv(k) % _P
    squared_offsets = sum(offset * offset for offset in range(-half, half + 1)) % _P
    if squared_offsets == 0:
        return None
    step_squared = (
        (sums[2] - k * center * center) * _inv(squared_offsets)
    ) % _P
    step = pow(step_squared, (_P + 1) // 4, _P)
    if step * step % _P != step_squared:
        return None
    roots = {
        (center + offset * step) % _P
        for offset in range(-half, half + 1)
    }
    if len(roots) != k:
        return None
    label_to_index = {label: index for index, label in enumerate(inst["labels"])}
    if any(root not in label_to_index for root in roots):
        return None
    return [int(label in roots) for label in inst["labels"]]


def _newton_vieta_candidate(inst):
    """Construction-aware reference algorithm, with an exact operation count."""
    sums = _power_sums_by_exponent(inst)
    k = sums.get(0, 0) % _P
    if not 1 <= k < min(inst["m"], _P):
        return None, 0
    if any(exponent not in sums for exponent in range(1, k + 1)):
        return None, 0

    elementary = [1]
    operations = 0
    for degree in range(1, k + 1):
        total = 0
        for index in range(1, degree + 1):
            term = elementary[degree - index] * sums[index] % _P
            operations += 1  # multiplication
            if index % 2:
                total = (total + term) % _P
            else:
                total = (total - term) % _P
            operations += 1  # addition/subtraction
        total = total * _inv(degree) % _P
        operations += 1
        elementary.append(total)

    # Monic polynomial with the selected labels as roots.
    polynomial = [1]
    for degree in range(1, k + 1):
        polynomial.append(((-1) ** degree * elementary[degree]) % _P)

    roots = set()
    for label in inst["labels"]:
        value = polynomial[0]
        for coefficient in polynomial[1:]:
            value = value * label % _P
            operations += 1
            value = (value + coefficient) % _P
            operations += 1
        if value == 0:
            roots.add(label)
    if len(roots) != k:
        return None, operations
    return [int(label in roots) for label in inst["labels"]], operations


def canonical_key(inst):
    """Canonicalize generator order, coordinate order, and affine label changes."""
    candidate = _symmetry_candidate(inst)
    if candidate is None:
        # Strong deterministic fallback for malformed/non-family instances.  It is
        # deliberately structural and contains neither seed nor rendered text.
        rows = sorted(
            (tuple(sorted(generator)), coefficient)
            for generator, coefficient in zip(inst["generators"], [0] * inst["n"])
        )
        payload = [inst["modulus"], inst["n"], inst["m"], rows,
                   sorted(inst["target"])]
        return hashlib.sha256(json.dumps(payload, separators=(",", ":")).encode()).hexdigest()

    selected = {label for label, bit in zip(inst["labels"], candidate) if bit}
    k = len(selected)
    center = sum(selected) * _inv(k) % _P
    centered = {((label - center) % _P) for label in selected}
    half = k // 2

    valid_steps = []
    for difference in centered:
        if difference == 0:
            continue
        trial = {
            offset * difference % _P
            for offset in range(-half, half + 1)
        }
        if trial == centered:
            valid_steps.append(difference)
    if not valid_steps:
        raise ValueError("could not canonicalize the recovered progression")

    forms = []
    for step in valid_steps:
        inverse_step = _inv(step)
        colored_points = sorted(
            (((label - center) * inverse_step % _P), int(label in selected))
            for label in inst["labels"]
        )
        forms.append(colored_points)
    canonical_points = min(forms)
    payload = {
        "p": _P,
        "n": inst["n"],
        "m": inst["m"],
        "exponents": sorted(inst["exponents"]),
        "colored_affine_points": canonical_points,
    }
    blob = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(blob.encode()).hexdigest()


def escalate(params):
    """Grow the coefficient haystack and sparse-interpolation work within caps."""
    current = {key: value for key, value in params.items() if not key.startswith("_")}
    n = current["n"]
    m = current["m"]
    k = current["k"]
    if n < 256:
        new_n = min(256, n + 40)
        new_k = min(99, k + 4)
        if new_k % 2 == 0:
            new_k += 1
        new_m = max(m + 12, new_k + 1)
        return {"n": new_n, "m": new_m, "k": new_k}
    if k < 99:
        new_k = min(99, k + 8)
        if new_k % 2 == 0:
            new_k -= 1
        return {"n": n, "m": max(m + 12, new_k + 1), "k": new_k}
    # More labels would make the coefficient vector exceed 256 atoms, while a
    # larger k would push the compact route toward the 300-operation cap.
    return "cap_bound"


def _candidate_from_indices(inst, indices):
    chosen = set(indices)
    return [int(index in chosen) for index in range(inst["n"])]


def _attack_outlier_checksum(inst):
    k = inst["target"][inst["exponents"].index(0)] % _P
    scores = []
    for index, generator in enumerate(inst["generators"]):
        checksum = sum((coordinate + 1) * value
                       for coordinate, value in enumerate(generator[:8])) % _P
        zero_count = sum(value == 0 for value in generator)
        scores.append(((zero_count, checksum, inst["labels"][index]), index))
    indices = [index for _, index in sorted(scores)[:k]]
    return _candidate_from_indices(inst, indices)


def _balanced_residue(value):
    value %= _P
    return min(value, _P - value)


def _attack_greedy_residual(inst):
    k = inst["target"][inst["exponents"].index(0)] % _P
    width = min(6, inst["m"])
    residual = list(inst["target"][:width])
    unused = set(range(inst["n"]))
    chosen = []
    for _ in range(k):
        best = min(
            unused,
            key=lambda index: (
                sum(_balanced_residue(residual[r] - inst["generators"][index][r])
                    for r in range(width)),
                index,
            ),
        )
        chosen.append(best)
        unused.remove(best)
        for coordinate in range(width):
            residual[coordinate] = (
                residual[coordinate] - inst["generators"][best][coordinate]
            ) % _P
    return _candidate_from_indices(inst, chosen)


def _attack_random_restart(inst, seed, restarts=256):
    rng = random.Random(seed ^ 0x6A09E667)
    k = inst["target"][inst["exponents"].index(0)] % _P
    last = None
    for _ in range(restarts):
        indices = rng.sample(range(inst["n"]), k)
        last = _candidate_from_indices(inst, indices)
        ok, _ = verify(inst, last)
        if ok:
            return last
    return last


def _attack_center_consecutive(inst):
    sums = _power_sums_by_exponent(inst)
    k = sums[0] % _P
    center = sums[1] * _inv(k) % _P
    half = k // 2
    assumed = {(center + offset) % _P for offset in range(-half, half + 1)}
    return [int(label in assumed) for label in inst["labels"]]


def _permuted_generators(inst, rng):
    order = list(range(inst["n"]))
    rng.shuffle(order)
    transformed = copy.deepcopy(inst)
    transformed["labels"] = [inst["labels"][old] for old in order]
    transformed["generators"] = [inst["generators"][old] for old in order]
    transformed["answer"] = [inst["answer"][old] for old in order]
    return transformed


def _permuted_coordinates(inst, rng):
    order = list(range(inst["m"]))
    rng.shuffle(order)
    transformed = copy.deepcopy(inst)
    transformed["exponents"] = [inst["exponents"][old] for old in order]
    transformed["target"] = [inst["target"][old] for old in order]
    transformed["generators"] = [
        [generator[old] for old in order]
        for generator in inst["generators"]
    ]
    return transformed


def _affine_labels(inst, multiplier, translation):
    if multiplier % _P == 0:
        raise ValueError("affine multiplier must be nonzero")
    transformed = copy.deepcopy(inst)
    transformed["labels"] = [
        (multiplier * label + translation) % _P for label in inst["labels"]
    ]
    transformed["generators"] = _generators(
        transformed["labels"], transformed["exponents"]
    )
    transformed["target"] = _linear_combination(
        transformed["generators"], transformed["answer"], transformed["m"]
    )
    return transformed


def _answer_atoms(value):
    if isinstance(value, dict):
        return sum(_answer_atoms(item) for item in value.values())
    if isinstance(value, (list, tuple)):
        return sum(_answer_atoms(item) for item in value)
    return 1


