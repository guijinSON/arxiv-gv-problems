def canonical_key(inst):
    """Canonicalize equation order and all affine relabellings of Z/nZ."""
    decoded = _decode_instance(inst)
    if decoded is None:
        return "malformed"
    n, prime, _generator, omega, _omega_inverse, _n_inverse, rhs = decoded
    omega_powers = [pow(omega, exponent, prime) for exponent in range(n)]
    best = None
    # Relabelling input coordinate j as u*j+t, gcd(u,n)=1, sends
    # y_k to omega^(t*k)*y_(u*k).  Enumerating the full affine group gives a
    # deterministic normal form and includes rotations, reflections, and all
    # their compositions.
    for unit in range(n):
        if math.gcd(unit, n) != 1:
            continue
        base = [rhs[(unit * frequency) % n] for frequency in range(n)]
        for translation in range(n):
            candidate = tuple(
                base[frequency]
                * omega_powers[(translation * frequency) % n]
                % prime
                for frequency in range(n)
            )
            if best is None or candidate < best:
                best = candidate
    payload = json.dumps([n, prime, omega, best], separators=(",", ":"))
    return hashlib.sha256(payload.encode("ascii")).hexdigest()


