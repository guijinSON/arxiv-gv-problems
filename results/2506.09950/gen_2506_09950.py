@functools.lru_cache(maxsize=None)
def _is_prime(value):
    if not isinstance(value, int) or isinstance(value, bool) or value < 2:
        return False
    if value % 2 == 0:
        return value == 2
    divisor = 3
    while divisor * divisor <= value:
        if value % divisor == 0:
            return False
        divisor += 2
    return True


@functools.lru_cache(maxsize=None)
def _valid_parameters(n, prime, generator):
    if not all(isinstance(v, int) and not isinstance(v, bool) for v in (n, prime, generator)):
        return False
    if n < 2 or n > 256 or n & (n - 1):
        return False
    if prime > 2013265921 or not _is_prime(prime) or (prime - 1) % n:
        return False
    if not 1 < generator < prime:
        return False
    omega = pow(generator, (prime - 1) // n, prime)
    return pow(omega, n, prime) == 1 and pow(omega, n // 2, prime) != 1


def _dft(values, omega, prime):
    """Direct exact transform, used for construction and independent checking."""
    n = len(values)
    powers = [pow(omega, exponent, prime) for exponent in range(n)]
    return [
        sum(values[j] * powers[(j * frequency) % n] for j in range(n)) % prime
        for frequency in range(n)
    ]


def _fft(values, omega, prime, counter=None):
    """Radix-2 transform used only by the compact/reference diagnostics."""
    n = len(values)
    if n == 1:
        return list(values)
    even = _fft(values[0::2], pow(omega, 2, prime), prime, counter)
    odd = _fft(values[1::2], pow(omega, 2, prime), prime, counter)
    out = [0] * n
    twiddle = 1
    for k in range(n // 2):
        product = twiddle * odd[k] % prime
        out[k] = (even[k] + product) % prime
        out[k + n // 2] = (even[k] - product) % prime
        if counter is not None:
            counter["field_operations"] += 3
        twiddle = twiddle * omega % prime
    return out


def _inverse_fft(rhs, omega_inverse, n_inverse, prime, counter=None):
    out = _fft(rhs, omega_inverse, prime, counter)
    scaled = []
    for value in out:
        scaled.append(value * n_inverse % prime)
        if counter is not None:
            counter["field_operations"] += 1
    return scaled


def _sorted_rhs(inst):
    equations = inst.get("equations")
    n = inst.get("n")
    prime = inst.get("prime")
    if not isinstance(equations, list) or not isinstance(n, int) or not isinstance(prime, int):
        return None
    if len(equations) != n:
        return None
    ordered = [None] * n
    for equation in equations:
        if not isinstance(equation, dict) or set(equation) != {"frequency", "rhs"}:
            return None
        frequency = equation["frequency"]
        rhs = equation["rhs"]
        if (
            not isinstance(frequency, int)
            or isinstance(frequency, bool)
            or not 0 <= frequency < n
            or ordered[frequency] is not None
            or not isinstance(rhs, int)
            or isinstance(rhs, bool)
            or not 0 <= rhs < prime
        ):
            return None
        ordered[frequency] = rhs
    return ordered if all(value is not None for value in ordered) else None


def _decode_instance(inst):
    if not isinstance(inst, dict):
        return None
    n = inst.get("n")
    prime = inst.get("prime")
    generator = inst.get("generator")
    omega = inst.get("omega")
    omega_inverse = inst.get("omega_inverse")
    n_inverse = inst.get("n_inverse")
    twiddles = inst.get("inverse_twiddles")
    if not _valid_parameters(n, prime, generator):
        return None
    expected_omega = pow(generator, (prime - 1) // n, prime)
    if omega != expected_omega or omega_inverse != pow(omega, prime - 2, prime):
        return None
    if n_inverse != pow(n, prime - 2, prime):
        return None
    expected_twiddles = [pow(omega_inverse, exponent, prime) for exponent in range(n // 2)]
    if twiddles != expected_twiddles:
        return None
    rhs = _sorted_rhs(inst)
    if rhs is None:
        return None
    return n, prime, generator, omega, omega_inverse, n_inverse, rhs


def make_instance(n, seed=0, prime=None, generator=None, **params):
    """Inverse-generate a unique finite-field polynomial system.

    The witness x is sampled first and y=DFT(x) is then evaluated exactly.  No
    solving, search, global RNG, file access, or external dependency is involved.
    """
    if prime is None or generator is None or params:
        raise ValueError("n, prime, and generator are the only supported parameters")
    if not _valid_parameters(n, prime, generator):
        raise ValueError("need power-of-two n dividing prime-1 and an adequate generator")
    if not isinstance(seed, int) or isinstance(seed, bool):
        raise ValueError("seed must be an integer")
    rng = random.Random(seed)
    answer = [rng.randrange(prime) for _ in range(n)]
    omega = pow(generator, (prime - 1) // n, prime)
    omega_inverse = pow(omega, prime - 2, prime)
    n_inverse = pow(n, prime - 2, prime)
    rhs = _dft(answer, omega, prime)
    equations = [
        {"frequency": frequency, "rhs": rhs[frequency]}
        for frequency in range(n)
    ]
    rng.shuffle(equations)
    return {
        "n": n,
        "prime": prime,
        "generator": generator,
        "omega": omega,
        "omega_inverse": omega_inverse,
        "n_inverse": n_inverse,
        "inverse_twiddles": [
            pow(omega_inverse, exponent, prime) for exponent in range(n // 2)
        ],
        "equations": equations,
        "answer": answer,
    }


