def _is_int(value):
    return isinstance(value, int) and not isinstance(value, bool)


def _validate_bits(n):
    if not _is_int(n) or n < 5 or n > 50:
        raise ValueError("n must be an integer in [5,50]")


def _compose(left_a, left_b, right_a, right_b, modulus):
    """Return left(right(x)) as an affine pair, exactly modulo modulus."""
    return (
        (left_a * right_a) % modulus,
        (left_a * right_b + left_b) % modulus,
    )


def _affine_power(a, b, exponent, modulus):
    """Return (A,B) with f**exponent(x)=A*x+B modulo modulus."""
    result_a, result_b = 1, 0
    base_a, base_b = a % modulus, b % modulus
    e = exponent
    while e:
        if e & 1:
            result_a, result_b = _compose(
                base_a, base_b, result_a, result_b, modulus
            )
        base_a, base_b = _compose(
            base_a, base_b, base_a, base_b, modulus
        )
        e >>= 1
    return result_a, result_b


def _jump_values(a, b, start, exponent, modulus):
    power_a, power_b = _affine_power(a, b, exponent, modulus)
    return (power_a * start + power_b) % modulus


def _jump(inst, exponent):
    return _jump_values(
        inst["multiplier"],
        inst["increment"],
        inst["start"],
        exponent,
        inst["modulus"],
    )


def _step(inst, label):
    return (
        inst["multiplier"] * label + inst["increment"]
    ) % inst["modulus"]


def _inverse_step(inst, label):
    modulus = inst["modulus"]
    inverse = pow(inst["multiplier"], -1, modulus)
    return (inverse * (label - inst["increment"])) % modulus


def _weight_from_coefficients(coefficients, distance):
    c0, c1, c2 = coefficients
    return c0 + c1 * distance + c2 * distance * distance


def _weight(inst, index):
    n_vertices = inst["vertex_count"]
    distance = min(index, n_vertices - 1 - index)
    return _weight_from_coefficients(inst["weight_coefficients"], distance)


def _sum_polynomial_weights(coefficients, count):
    """sum_{d=0}^{count-1} c0+c1*d+c2*d^2, exactly."""
    c0, c1, c2 = coefficients
    linear = count * (count - 1) // 2
    squares = count * (count - 1) * (2 * count - 1) // 6
    return c0 * count + c1 * linear + c2 * squares


def _weight_totals(vertex_count, coefficients):
    # vertex_count = 2*h+1; distances 0,...,h-1 occur twice and h once.
    h = (vertex_count - 1) // 2
    half = _sum_polynomial_weights(coefficients, h)
    center_weight = _weight_from_coefficients(coefficients, h)
    return half, center_weight, 2 * half + center_weight


def make_instance(n, seed=0, **params):
    """Construct a succinct corridor path and its Lemma 8 witness.

    The full-period recurrence and symmetric positive weights are sampled first.
    The unique central label is obtained by composing the recurrence, an identity
    valid independently of the certificate search problem.  No centroid scan or
    answer search is performed during generation.
    """
    if params:
        raise TypeError("unknown parameters: " + ", ".join(sorted(params)))
    _validate_bits(n)
    if not _is_int(seed):
        raise ValueError("seed must be an integer")

    rng = random.Random(seed)
    modulus = 1 << n
    # Use a non-special odd prefix length of the full affine cycle.  In
    # particular, the middle exponent is not a power-of-two half-cycle where a
    # 2-adic shortcut would reveal the answer.  A separate RNG makes the same
    # seed scale to essentially twice as many vertices when n increases by one.
    size_rng = random.Random(seed ^ 0x230700704)
    size_slot = size_rng.randrange(1 << 16)
    n_slots = modulus // 16
    vertex_count = 3 * modulus // 4 + 1 + 2 * (size_slot * n_slots // (1 << 16))
    # Hull-Dobell for modulus 2^n: b odd and a == 1 (mod 4) give one full cycle.
    multiplier = 1 + 4 * rng.randrange(1, modulus // 4)
    increment = 2 * rng.randrange(modulus // 2) + 1
    start = rng.randrange(modulus)

    # Wide coefficient ranges make structurally unrelated seeds distinct.  All
    # coefficients are positive, which makes the central weighted centroid unique.
    coefficients = [rng.randrange(1, 1_000_000_001) for _ in range(3)]

    middle_index = (vertex_count - 1) // 2
    end = _jump_values(
        multiplier, increment, start, vertex_count - 1, modulus
    )
    first_unused = _jump_values(
        multiplier, increment, start, vertex_count, modulus
    )
    centroid = _jump_values(
        multiplier, increment, start, middle_index, modulus
    )
    neighbor = (multiplier * centroid + increment) % modulus
    half_weight, center_weight, total_weight = _weight_totals(vertex_count, coefficients)

    return {
        "paper_object": "Lemma 8 exchange separator in corridor tree T(P)",
        "bits": n,
        "modulus": modulus,
        "vertex_count": vertex_count,
        "multiplier": multiplier,
        "increment": increment,
        "start": start,
        "end": end,
        "first_unused_label": first_unused,
        "weight_coefficients": coefficients,
        "half_weight": half_weight,
        "center_weight": center_weight,
        "total_weight": total_weight,
        "answer": {"centroid": centroid, "neighbor": neighbor},
    }


