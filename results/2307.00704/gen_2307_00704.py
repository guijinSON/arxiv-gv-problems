def parse_answer(text):
    """Extract the required JSON object; return None on every malformed input."""
    if not isinstance(text, str):
        return None
    match = _ANSWER_RE.search(text)
    if not match:
        return None
    payload = match.group(1).strip()
    if payload.startswith("```"):
        payload = re.sub(r"^```(?:json)?\s*", "", payload, flags=re.I)
        payload = re.sub(r"\s*```$", "", payload)
    try:
        answer = json.loads(payload)
    except (TypeError, ValueError, json.JSONDecodeError):
        return None
    if not isinstance(answer, dict):
        return None
    if set(answer) != {"centroid", "neighbor"}:
        return None
    if not _is_int(answer["centroid"]) or not _is_int(answer["neighbor"]):
        return None
    return answer


def _expected_centroid(inst):
    return _jump(inst, (inst["vertex_count"] - 1) // 2)


def verify(inst, answer):
    """Check any valid oriented Lemma 8 separator, never the planted answer."""
    if answer == {} or answer == [] or answer == "":
        return False, "answer is empty"
    if not isinstance(answer, dict) or set(answer) != {"centroid", "neighbor"}:
        return False, "answer must have exactly the centroid and neighbor fields"
    centroid = answer["centroid"]
    neighbor = answer["neighbor"]
    if not _is_int(centroid) or not _is_int(neighbor):
        return False, "both labels must be integers"
    modulus = inst["modulus"]
    if not 0 <= centroid < modulus:
        return False, "centroid label is outside the allowed residue range"
    if not 0 <= neighbor < modulus:
        return False, "neighbor label is outside the allowed residue range"
    if centroid == inst["first_unused_label"] or neighbor == inst["first_unused_label"]:
        return False, "the stated first-unused label is not a corridor-tree vertex"
    if centroid == neighbor:
        return False, "centroid and neighbor must be distinct"

    actual_centroid = _expected_centroid(inst)
    if centroid != actual_centroid:
        return False, "the first label is not the unique weighted centroid"

    previous_label = _inverse_step(inst, centroid)
    next_label = _step(inst, centroid)
    if neighbor not in (previous_label, next_label):
        return False, "the second label is not adjacent to the centroid"

    # The positive mirror-symmetric weights give equal left/right component
    # weights.  Verify all four Lemma 8 requirements from exact closed forms.
    n_vertices = inst["vertex_count"]
    side_vertices = (n_vertices - 1) // 2
    side_weight = _sum_polynomial_weights(
        inst["weight_coefficients"], side_vertices
    )
    center_weight = _weight_from_coefficients(
        inst["weight_coefficients"], side_vertices
    )
    total_weight = 2 * side_weight + center_weight
    if total_weight != inst["total_weight"]:
        return False, "instance total weight is inconsistent"
    if 2 * side_weight > total_weight:
        return False, "deleting the proposed centroid leaves an overweight component"
    selected_vertices = side_vertices + 1
    if 3 * selected_vertices < n_vertices:
        return False, "selected contiguous subtree has fewer than N/3 vertices"
    selected_weight = side_weight + center_weight
    if 2 * selected_weight > total_weight + 2 * center_weight:
        return False, "selected contiguous subtree exceeds W/2 plus w(c)"
    return True, "ok"


def _candidate_index_bounds(inst):
    """Inclusive index range for a left-selecting structure-valid candidate.

    Write N=2h+1.  A pair selecting the left side meets the N/3 size bound
    exactly when i >= ceil(N/3)-1.  It meets the weight bound exactly when
    i <= h: before the centre the chosen prefix weighs less than W/2, while
    after the centre reflection symmetry and positive centre weight make the
    prefix too heavy.  Right-selecting candidates are the reflected range.
    """
    n_vertices = inst["vertex_count"]
    first = (n_vertices + 2) // 3 - 1
    middle = (n_vertices - 1) // 2
    return first, middle


def random_candidate(inst, rng):
    """Uniformly sample an oriented edge satisfying every non-centroid rule."""
    first, middle = _candidate_index_bounds(inst)
    reflected_index = rng.randrange(first, middle + 1)
    if rng.randrange(2) == 0:
        centroid_index = reflected_index
        centroid = _jump(inst, centroid_index)
        neighbor = _inverse_step(inst, centroid)
    else:
        centroid_index = inst["vertex_count"] - 1 - reflected_index
        centroid = _jump(inst, centroid_index)
        neighbor = _step(inst, centroid)
    return {"centroid": centroid, "neighbor": neighbor}


def search_space(inst):
    first, middle = _candidate_index_bounds(inst)
    return 2 * (middle - first + 1)


def enumerate_all(inst):
    """Brute-force all oriented edges only for genuinely small demo instances."""
    if search_space(inst) > 20_000:
        return None
    count = 0
    label = inst["start"]
    for _ in range(inst["vertex_count"] - 1):
        nxt = _step(inst, label)
        for candidate in (
            {"centroid": label, "neighbor": nxt},
            {"centroid": nxt, "neighbor": label},
        ):
            if verify(inst, candidate)[0]:
                count += 1
        label = nxt
    return count


def canonical_key(inst):
    """Canonical under arbitrary label renaming and reversal of the corridor path.

    An unlabeled path with these mirror-symmetric weights is determined by its
    length and polynomial weight sequence.  The affine presentation is only a
    vertex relabeling and is therefore deliberately absent from this key.
    """
    structural = {
        "vertex_count": inst["vertex_count"],
        "weight_coefficients": list(inst["weight_coefficients"]),
    }
    blob = json.dumps(structural, separators=(",", ":"), sort_keys=True)
    return "corridor-path:" + hashlib.sha256(blob.encode("ascii")).hexdigest()


def escalate(params):
    """Double the represented path while the two-label certificate stays fixed."""
    if not isinstance(params, dict) or "n" not in params:
        return None
    n = params["n"]
    if not _is_int(n):
        return None
