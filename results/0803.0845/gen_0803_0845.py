def _binomial_polynomial_values(coefficients: list[int], count: int) -> list[int]:
    """Evaluate sum_k coefficients[k] * binomial(i,k), exactly."""

    values = []
    for i in range(count):
        value = 0
        choose = 1
        for k, coefficient in enumerate(coefficients):
            if k > i:
                break
            if k:
                choose = choose * (i - k + 1) // k
            value += coefficient * choose
        values.append(value)
    return values


def _superincreasing_prefix(count: int, rng: random.Random) -> list[int]:
    values: list[int] = []
    total = 0
    for _ in range(count):
        value = total + rng.randint(1, 3)
        values.append(value)
        total += value
    return values


def make_instance(
    n: int,
    seed: int = 0,
    q_bits: int = 104,
    quotient_bits: int = 768,
    **params,
) -> dict:
    """Construct a native Problem-4 instance and its pseudo-key certificate.

    There are n public integers.  The exact remainders of the first n-1 are
    supplied.  The quotient sequence is sampled first in the binomial basis;
    its (n-2)-nd forward difference is one.  Multiplication by a sampled q then
    makes that forward difference exactly q.  No instance is solved.
    """

    del params
    if not isinstance(n, int) or n < 4:
        raise ValueError("n must be an integer at least 4")
    if not isinstance(q_bits, int) or q_bits < max(8, n + 2):
        raise ValueError("q_bits must be an integer large enough for the remainders")
    if not isinstance(quotient_bits, int) or quotient_bits < 8:
        raise ValueError("quotient_bits must be an integer at least 8")

    rng = random.Random(seed)
    q_lower = 1 << (q_bits - 1)
    q_upper = 1 << q_bits
    q = rng.randrange(q_lower, q_upper)
    if q % 2 == 0:
        q += 1
    if q >= q_upper:
        q -= 2

    exact_count = n - 1
    degree = exact_count - 1
    remainders = _superincreasing_prefix(exact_count, rng)
    prefix_sum = sum(remainders)
    interval_low = prefix_sum + 1
    interval_width = max(2, prefix_sum // 3)
    interval_high = interval_low + interval_width  # closed endpoint
    last_remainder = rng.randint(interval_low, interval_high)
    if prefix_sum + last_remainder >= q:
        raise ValueError("q_bits is too small for this n's superincreasing sequence")

    base = 1 << quotient_bits
    # Random lower-order coefficients hide the invariant.  The large positive
    # constant dominates every signed lower term on i=0,...,degree.
    coefficients = [0] * (degree + 1)
    coefficients[0] = rng.randrange(4 * base * (1 << degree), 5 * base * (1 << degree))
    for k in range(1, degree):
        coefficient = rng.randrange(-base + 1, base)
        coefficients[k] = coefficient if coefficient else 1
    coefficients[degree] = 1
    quotients = _binomial_polynomial_values(coefficients, exact_count)
    if min(quotients) <= 0:
        raise AssertionError("positive-offset construction failed")

    exact_pairs = [
        [q * quotient + remainder, remainder]
        for quotient, remainder in zip(quotients, remainders)
    ]
    rng.shuffle(exact_pairs)
    last_quotient = rng.randrange(4 * base * (1 << degree), 5 * base * (1 << degree))
    last_public_integer = q * last_quotient + last_remainder

    return {
        "paper": "arXiv:0803.0845",
        "family": "Problem 4 pseudo-key from prescribed Euclidean remainders",
        "n": n,
        "q_bits": q_bits,
        "quotient_bits": quotient_bits,
        "q_interval": [q_lower, q_upper],
        "exact_pairs": exact_pairs,
        "last_public_integer": last_public_integer,
        "last_remainder_interval": [interval_low, interval_high],
        "answer": {"q": q, "last_remainder": last_remainder},
    }


