"""Perfect covers in 2-flat multiplicative-coset hypergraphs.

The paper's Theorem 1 characterizes d-flat hypergraphs by the maximum chain
length in their intersection closure.  Here every edge has one left and one
right endpoint.  Its intersection closure contains only the universe,
2-edges, singleton intersections, and the empty set, so its chain length is at
most three: every generated instance is 2-flat (3-semi-ladder-free).

The certificate is generated by composition of identities.  Two multiplicative
cosets of an order-n subgroup of GF(q)^* are the vertex classes, and every
chosen multiplier maps the left coset bijectively to the right coset.  Each
multiplier therefore supplies a perfect cover before edge IDs are shuffled.
No search algorithm is run to obtain ``inst["answer"]``.
"""

