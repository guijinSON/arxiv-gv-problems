def _hopcroft_karp(inst):
    """Return (matching edge IDs or None, edge scans, BFS/DFS phases)."""
    n = inst["n"]
    adjacency = [sorted(row) for row in inst["left_adjacency"]]
    pair_left = [-1] * n
    pair_right = [-1] * n
    pair_edge = [-1] * n
    distance = [0] * n
    scans = 0
    phases = 0

    def bfs():
        nonlocal scans, phases
        phases += 1
        queue = []
        for u in range(n):
            if pair_left[u] == -1:
                distance[u] = 0
                queue.append(u)
            else:
                distance[u] = -1
        found = False
        head = 0
        while head < len(queue):
            u = queue[head]
            head += 1
            for edge_id in adjacency[u]:
                scans += 1
                v = inst["edges"][edge_id][1]
                mate = pair_right[v]
                if mate == -1:
                    found = True
                elif distance[mate] < 0:
                    distance[mate] = distance[u] + 1
                    queue.append(mate)
        return found

    def dfs(u):
        nonlocal scans
        for edge_id in adjacency[u]:
            scans += 1
            v = inst["edges"][edge_id][1]
            mate = pair_right[v]
            if mate == -1 or (distance[mate] == distance[u] + 1 and dfs(mate)):
                pair_left[u] = v
                pair_right[v] = u
                pair_edge[u] = edge_id
                return True
        distance[u] = -1
        return False

    size = 0
    while bfs():
        gained = 0
        for u in range(n):
            if pair_left[u] == -1 and dfs(u):
                size += 1
                gained += 1
        if gained == 0:
            break
    return (sorted(pair_edge) if size == n else None), scans, phases


def _random_restart_attack(inst, seed, restarts=256):
    rng = random.Random(seed)
    last = None
    for _ in range(restarts):
        last = random_candidate(inst, rng)
        if _candidate_is_cover(inst, last):
            return last
    return last


def _sample_guess_hits(inst, rng, trials):
    """Sample the random_candidate prior, stopping a trial at first collision.

    Once two chosen edges share a right endpoint the candidate cannot verify;
    the ungenerated suffix is immaterial and marginalizing it preserves exactly
    the same product distribution as ``random_candidate``.
    """
    rows = inst["left_adjacency"]
    edges = inst["edges"]
    hits = 0
    for _ in range(trials):
        used_right = set()
        for row in rows:
            right = edges[rng.choice(row)][1]
            if right in used_right:
                break
            used_right.add(right)
        else:
            hits += 1
    return hits


def _relabel_instance(inst, rng):
    """Independently reorder both parts and all edges, carrying the answer."""
    n = inst["n"]
    left_order = list(range(n))
    right_order = list(range(n))
    edge_order = list(range(len(inst["edges"])))
    rng.shuffle(left_order)
    rng.shuffle(right_order)
    rng.shuffle(edge_order)
    left_old_to_new = [0] * n
    right_old_to_new = [0] * n
    edge_old_to_new = [0] * len(edge_order)
    for new, old in enumerate(left_order):
        left_old_to_new[old] = new
    for new, old in enumerate(right_order):
        right_old_to_new[old] = new
    for new, old in enumerate(edge_order):
        edge_old_to_new[old] = new

    transformed = dict(inst)
    transformed["left_values"] = [inst["left_values"][old] for old in left_order]
    transformed["right_values"] = [inst["right_values"][old] for old in right_order]
    transformed["edges"] = [
        [left_old_to_new[inst["edges"][old][0]],
         right_old_to_new[inst["edges"][old][1]]]
        for old in edge_order
    ]
    transformed["left_adjacency"] = [[] for _ in range(n)]
    for edge_id, (left, _right) in enumerate(transformed["edges"]):
        transformed["left_adjacency"][left].append(edge_id)
    transformed["answer"] = sorted(edge_old_to_new[e] for e in inst["answer"])
    transformed["anchor_left_index"] = left_old_to_new[inst["anchor_left_index"]]
    return transformed


def _find_replacement_corruption(inst):
    answer = list(inst["answer"])
    chosen = set(answer)
    left, _ = _endpoint_adjacency(inst)
    target_left = inst["edges"][answer[0]][0]
    replacement = next(e for e in left[target_left] if e not in chosen)
    answer[0] = replacement
    return answer


def selftest():
    """Run all mandatory correctness, resistance, scaling, and audit gates."""
    report = {
        "paper": "2311.00466",
        "track": TRACK,
        "shipping_difficulty": SHIPPING_DIFFICULTY,
        "shipping_params": dict(DIFFICULTY[SHIPPING_DIFFICULTY]),
    }

    # G1: every preset across four seeds, plus JSON-native certificates.
    g1_attempts = 0
    g1_failures = []
    for preset, params in DIFFICULTY.items():
        for seed in (0, 1, 7, 19):
            inst = make_instance(seed=seed, **params)
            ok, reason = verify(inst, inst["answer"])
            g1_attempts += 1
            if not ok:
                g1_failures.append([preset, seed, reason])
            if json.loads(json.dumps(inst["answer"])) != inst["answer"]:
                g1_failures.append([preset, seed, "answer is not JSON-native"])
    report["G1_planted_verifies"] = {
        "pass": not g1_failures,
        "verified": g1_attempts - len(g1_failures),
        "attempts": g1_attempts,
        "failures": g1_failures,
    }

    shipping = make_instance(seed=20260905, **DIFFICULTY[SHIPPING_DIFFICULTY])

    # G2: five different corruption classes must reach five different reasons.
    corruptions = {
        "drop_one": shipping["answer"][:-1],
        "replace_one": _find_replacement_corruption(shipping),
        "duplicate": shipping["answer"][:-1] + [shipping["answer"][0]],
        "empty": [],
        "out_of_range": shipping["answer"][:-1] + [len(shipping["edges"])],
    }
    g2_results = {}
    reasons = set()
    for name, candidate in corruptions.items():
        ok, reason = verify(shipping, candidate)
        g2_results[name] = {"rejected": not ok, "reason": reason}
        if not ok:
            reasons.add(reason)
    report["G2_rejects_corruption"] = {
        "pass": all(x["rejected"] for x in g2_results.values()) and len(reasons) == 5,
        "distinct_reasons": len(reasons),
        "cases": g2_results,
    }

    # G3: realistic prose/fence round trip and malformed cases.
    payload = json.dumps(shipping["answer"], separators=(",", ":"))
    model_style = (
        "I matched every endpoint exactly once.\n\n"
        "<answer>\n```json\n" + payload + "\n```\n</answer>\n"
        "The list is in edge-ID order."
    )
    parsed = parse_answer(model_style)
    garbage = ["", "[1,2]", "<answer>oops</answer>",
               "<answer>[1,true,3]</answer>"]
    garbage_rejected = sum(parse_answer(x) is None for x in garbage)
    report["G3_round_trip"] = {
        "pass": parsed == shipping["answer"] and garbage_rejected == len(garbage),
        "model_style_round_trip": parsed == shipping["answer"],
        "garbage_rejected": garbage_rejected,
        "garbage_attempts": len(garbage),
    }

    # G4: structure-aware candidates already choose exactly one edge per left.
    guess_total = 200_000
    guess_hits = 0
    guess_rng = random.Random(0x231100466)
    t0 = time.perf_counter()
    guess_hits = _sample_guess_hits(shipping, guess_rng, guess_total)
    guess_elapsed = time.perf_counter() - t0
    guess_probability = guess_hits / guess_total
    report["G4_guess_resistance"] = {
        "pass": guess_probability < 1e-6,
        "hits": guess_hits,
        "total": guess_total,
        "observed_probability": guess_probability,
        "candidate_space": search_space(shipping),
        "candidate_space_bits": search_space(shipping).bit_length(),
        "prior": "uniform one-incident-edge choice independently at each left vertex",
        "wall_clock_sec": round(guess_elapsed, 6),
    }

    # G5: shipping density estimate plus exact demo count and reference cost.
    demo = make_instance(seed=3, **DIFFICULTY["demo"])
    demo_count = enumerate_all(demo)
    t0 = time.perf_counter()
    reference_answer, reference_scans, reference_phases = _hopcroft_karp(shipping)
    reference_elapsed = time.perf_counter() - t0
    ref_ok = reference_answer is not None and verify(shipping, reference_answer)[0]
    t0 = time.perf_counter()
    baseline_candidate = _random_restart_attack(shipping, 88172645463325252, 256)
    baseline_elapsed = time.perf_counter() - t0
    baseline_ok = _candidate_is_cover(shipping, baseline_candidate)
    report["G5_density_and_baseline"] = {
        "pass": demo_count is not None and ref_ok and not baseline_ok,
        "shipping_density_hits": guess_hits,
        "shipping_density_samples": guess_total,
        "shipping_density_fraction": guess_probability,
        "baseline_restarts": 256,
        "baseline_wall_clock_sec": round(baseline_elapsed, 6),
        "reference_edge_scans": reference_scans,
        "reference_wall_clock_sec": round(reference_elapsed, 6),
        "shipping_density": {
            "hits": guess_hits,
            "samples": guess_total,
            "observed_fraction": guess_probability,
        },
        "demo_exact_valid_answers": demo_count,
        "demo_candidate_space": search_space(demo),
        "strongest_failing_attack": {
            "name": "structure-aware random restart",
            "restarts": 256,
            "wall_clock_sec": round(baseline_elapsed, 6),
            "success": baseline_ok,
        },
        "reference_cost": {
            "name": "Hopcroft-Karp",
            "wall_clock_sec": round(reference_elapsed, 6),
            "edge_scans": reference_scans,
            "phases": reference_phases,
            "verified": ref_ok,
        },
    }

    # G6: four failed no-tool/generic probes over eight fresh seeds.  The
    # successful polynomial reference algorithm is deliberately separate.
    attack_names = (
        "outlier_lowest_edge_id",
        "greedy_smallest_unused_right",
        "random_restart_256",
        "by_hand_smallest_integer_gap",
    )
    successes = {name: 0 for name in attack_names}
    attempts = {name: 0 for name in attack_names}
    reference_successes = 0
    reference_scans_all = 0
    reference_phases_all = 0
    reference_times = []
    for seed in range(101, 109):
        inst = make_instance(seed=seed, **DIFFICULTY[SHIPPING_DIFFICULTY])
        candidates = {
            "outlier_lowest_edge_id": _attack_first_edge(inst),
            "greedy_smallest_unused_right": _attack_greedy_smallest_right(inst),
            "random_restart_256": _random_restart_attack(inst, seed ^ 0xA5A5, 256),
            "by_hand_smallest_integer_gap": _attack_local_gap(inst),
        }
        for name, candidate in candidates.items():
            attempts[name] += 1
            if _candidate_is_cover(inst, candidate):
                successes[name] += 1
        t0 = time.perf_counter()
        found, scans, phases = _hopcroft_karp(inst)
        reference_times.append(time.perf_counter() - t0)
        reference_scans_all += scans
        reference_phases_all += phases
        if found is not None and verify(inst, found)[0]:
            reference_successes += 1
    attacks = {
        name: {"successes": successes[name], "attempts": attempts[name]}
        for name in attack_names
    }
    all_failed = all(item["successes"] == 0 and item["attempts"] >= 8
                     for item in attacks.values())
    report["G6_adversary_panel"] = {
        "pass": all_failed and reference_successes == 8,
        "attacks": attacks,
        "reference_algorithm": {
            "name": "Hopcroft-Karp bipartite matching",
            "complexity": "O(|E| sqrt(|V|))",
            "wall_clock_sec_mean": round(sum(reference_times) / len(reference_times), 6),
            "wall_clock_sec_max": round(max(reference_times), 6),
            "operations": reference_scans_all,
            "edge_scans_mean": round(reference_scans_all / 8, 2),
            "phases_mean": round(reference_phases_all / 8, 2),
            "solves": f"{reference_successes}/8, as expected",
        },
    }

    # G7: n really enlarges the subgroup and answer language.  q-1 is divisible
    # by twice every non-demo preset n used here.
    doubled_params = dict(DIFFICULTY[SHIPPING_DIFFICULTY])
    doubled_params["n"] *= 2
    doubled = make_instance(seed=73, **doubled_params)
    doubled_ok = verify(doubled, doubled["answer"])[0]
    report["G7_scales"] = {
        "pass": doubled_ok and doubled["n"] > shipping["n"]
                and search_space(doubled) > search_space(shipping),
        "shipping_n": shipping["n"],
        "doubled_n": doubled["n"],
        "doubled_planted_verifies": doubled_ok,
        "shipping_space_bits": search_space(shipping).bit_length(),
        "doubled_space_bits": search_space(doubled).bit_length(),
    }

    # G8: independent part reorderings, edge reorderings, compositions, and
    # carried certificates; unrelated seeds must retain distinct invariants.
    invariant_checks = 0
    carried_checks = 0
    for seed in range(20):
        inst = make_instance(seed=2000 + seed, **DIFFICULTY[SHIPPING_DIFFICULTY])
        original_key = canonical_key(inst)
        transformed = inst
        for round_no in range(3):
            transformed = _relabel_instance(
                transformed, random.Random(90000 + 17 * seed + round_no))
            invariant_checks += 1
            if canonical_key(transformed) != original_key:
                break
            if verify(transformed, transformed["answer"])[0]:
                carried_checks += 1
    unrelated_keys = [
        canonical_key(make_instance(seed=5000 + seed,
                                    **DIFFICULTY[SHIPPING_DIFFICULTY]))
        for seed in range(20)
    ]
    distinct_keys = len(set(unrelated_keys))
    report["G8_canonical_key"] = {
        "pass": invariant_checks == 60 and carried_checks == 60 and distinct_keys == 20,
        "invariant_relabellings": invariant_checks,
        "invariant_successes": carried_checks,
        "carried_certificate_verifies": carried_checks,
        "unrelated_instances": 20,
        "distinct_keys": distinct_keys,
        "transformations": [
            "left-vertex input reordering",
            "right-vertex input reordering",
            "edge-ID reordering",
            "threefold compositions of all three",
        ],
        "key_strength": (
            "exact pairwise-neighborhood intersections plus the normalized "
            "finite-field multiplier-layer pattern; not a complete GI canonical form"
        ),
    }

    # G9(a,b) are recorded diagnostics; only the exact size/effort caps gate.
    compact = json.dumps(shipping["answer"], separators=(",", ":"))
    answer_chars = len(compact)
    answer_tokens = math.ceil(answer_chars / 4)
    answer_elements = len(shipping["answer"])
    intended_operations = shipping["n"] + 1
    within_caps = (answer_chars <= 2000 and answer_elements <= 256
                   and intended_operations <= 300)
    arms = {
        name: dict(G9_EVIDENCE[name])
        for name in ("bare", "hinted", "placebo")
    }
    hinted_rate = arms["hinted"]["solved"] / max(1, arms["hinted"]["attempts"])
    placebo_rate = arms["placebo"]["solved"] / max(1, arms["placebo"]["attempts"])
    report["G9_no_tool_suitability"] = {
        "pass": within_caps,
        "arms": arms,
        "hinted_minus_placebo": round(hinted_rate - placebo_rate, 6),
        "hinted_verdict": G9_EVIDENCE["hinted_verdict"],
        "answer_chars": answer_chars,
        "answer_tokens": answer_tokens,
        "answer_elements": answer_elements,
        "intended_route_operations": intended_operations,
        "caps": {"chars": 2000, "elements": 256, "operations": 300},
    }

    report["pass"] = all(
        value.get("pass") is True
        for key, value in report.items()
        if key.startswith("G") and isinstance(value, dict)
    )
    return report


