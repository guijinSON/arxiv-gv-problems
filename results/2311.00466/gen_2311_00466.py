def parse_answer(text):
    """Extract the last tagged JSON integer list, tolerating prose and fences."""
    if not isinstance(text, str):
        return None
    matches = re.findall(r"<answer\b[^>]*>(.*?)</answer\s*>", text,
                         flags=re.IGNORECASE | re.DOTALL)
    if not matches:
        return None
    payload = matches[-1].strip()
    payload = re.sub(r"^```(?:json)?\s*", "", payload, flags=re.IGNORECASE)
    payload = re.sub(r"\s*```$", "", payload)
    try:
        value = json.loads(payload)
    except (TypeError, ValueError, json.JSONDecodeError):
        return None
    if not isinstance(value, list):
        return None
    if any(isinstance(x, bool) or not isinstance(x, int) for x in value):
        return None
    return value


def verify(inst, answer):
    """Check a perfect cover from public incidence only; never inspect the plant."""
    if not isinstance(answer, list):
        return False, "answer must be a JSON list of edge IDs"
    if not answer:
        return False, "answer is empty"
    n = inst["n"]
    if len(answer) != n:
        return False, f"wrong edge count: expected {n}, got {len(answer)}"
    if any(isinstance(x, bool) or not isinstance(x, int) for x in answer):
        return False, "every edge ID must be an integer"
    if len(set(answer)) != n:
        return False, "duplicate edge ID"
    m = len(inst["edges"])
    if any(x < 0 or x >= m for x in answer):
        return False, f"edge ID outside the inclusive range 0..{m-1}"

    left_seen = set()
    right_seen = set()
    for edge_id in answer:
        left, right = inst["edges"][edge_id]
        if left in left_seen:
            return False, f"left vertex {left} is covered more than once"
        if right in right_seen:
            return False, f"right vertex {right} is covered more than once"
        left_seen.add(left)
        right_seen.add(right)
    if len(left_seen) != n or len(right_seen) != n:
        return False, "not every vertex is covered"
    return True, "ok"


def random_candidate(inst, rng):
    """Sample uniformly from choices with exactly one edge at every left vertex."""
    if not isinstance(rng, random.Random):
        raise TypeError("rng must be an instance of random.Random")
    # ``left_adjacency`` is public, derivable instance data stored to keep the
    # mandatory 200k-sample density measurement linear in n rather than |E|.
    return [rng.choice(row) for row in inst["left_adjacency"]]


def search_space(inst):
    """The exact size of the structure-aware one-edge-per-left language."""
    return inst["degree"] ** inst["n"]


def enumerate_all(inst):
    """Count perfect covers exactly when at most one million candidates exist."""
    space = search_space(inst)
    if space > 1_000_000:
        return None
    left, _ = _endpoint_adjacency(inst)
    count = 0
    for candidate in itertools.product(*left):
        if _candidate_is_cover(inst, candidate):
            count += 1
    return count


def canonical_key(inst):
    """Hash exact incidence invariants, never the seed, rendering, or labels."""
    left, right = _endpoint_adjacency(inst)
    left_neighbours = [set(inst["edges"][e][1] for e in row) for row in left]
    right_neighbours = [set(inst["edges"][e][0] for e in row) for row in right]

    def intersection_profile(neighbourhoods):
        return sorted(
            len(neighbourhoods[i] & neighbourhoods[j])
            for i in range(len(neighbourhoods))
            for j in range(i + 1, len(neighbourhoods))
        )

    invariant = {
        "parts": [len(left), len(right)],
        "degrees_left": sorted(map(len, left)),
        "degrees_right": sorted(map(len, right)),
        "left_pair_intersections": intersection_profile(left_neighbours),
        "right_pair_intersections": intersection_profile(right_neighbours),
    }
    # The field values are intrinsic vertex labels in this family (list indices
    # are merely presentation).  Quotients are constant on multiplier layers.
    # Dividing the quotient set by each of its own elements and taking the least
    # result removes the arbitrary relative scaling of the two vertex cosets.
    q = inst["q"]
    ratios = sorted({
        inst["right_values"][v] * pow(inst["left_values"][u], -1, q) % q
        for u, v in inst["edges"]
    })
    normalized_ratios = min(
        tuple(sorted(r * pow(base, -1, q) % q for r in ratios))
        for base in ratios
    )
    invariant["normalized_multiplier_layers"] = normalized_ratios
    blob = json.dumps(invariant, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(blob.encode("ascii")).hexdigest()


