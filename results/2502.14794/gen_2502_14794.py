def _normalize_cycle(order: list[int]) -> list[int]:
    """Choose the unique rotation/reversal with 0 first and forward < backward."""
    at = order.index(0)
    rotated = order[at:] + order[:at]
    reversed_order = [rotated[0]] + list(reversed(rotated[1:]))
    return min(rotated, reversed_order)


def _make_adjacency(n: int, edges: list[list[int]]) -> tuple[list[list[int]], list[int]]:
    adjacency = [[] for _ in range(n)]
    masks = [0] * n
    for u, v in edges:
        adjacency[u].append(v)
        adjacency[v].append(u)
        masks[u] |= 1 << v
        masks[v] |= 1 << u
    for row in adjacency:
        row.sort()
    return adjacency, masks


def make_instance(n: int, seed: int = 0, **params) -> dict:
    """Inverse-generate a near-threshold host and its square-cycle witness."""
    noise_factor_num = params.pop("noise_factor_num", 102)
    if params:
        raise ValueError(f"unknown parameters: {sorted(params)}")
    if isinstance(n, bool) or not isinstance(n, int):
        raise ValueError("n must be an integer")
    if n < 8:
        raise ValueError("n must be at least 8")
    if n > 256:
        raise ValueError("n exceeds the supported 256-vertex bound")
    if isinstance(noise_factor_num, bool) or not isinstance(noise_factor_num, int):
        raise ValueError("noise_factor_num must be an integer percentage")
    if not 90 <= noise_factor_num <= 120:
        raise ValueError("noise_factor_num must lie between 90 and 120")

    rng = random.Random(seed)
    relabel = list(range(n))
    rng.shuffle(relabel)

    plant = set()
    for i in range(n):
        for jump in (1, 2):
            plant.add(tuple(sorted((relabel[i], relabel[(i + jump) % n]))))
    if len(plant) != 2 * n:
        raise AssertionError("cycle-square construction did not have 2n edges")

    possible = [
        (u, v)
        for u in range(n)
        for v in range(u + 1, n)
        if (u, v) not in plant
    ]
    total_pairs = n * (n - 1) // 2
    p = noise_factor_num / 100.0 * math.sqrt(math.e / n)
    target_edges = max(2 * n, min(total_pairs, round(p * total_pairs)))
    extra = target_edges - 2 * n
    decoys = rng.sample(possible, extra)
    edge_set = plant | set(decoys)
    # Sort before shuffling so the same (n, seed, params) does not depend on
    # implementation-specific set iteration order.
    edges = [list(edge) for edge in sorted(edge_set)]
    rng.shuffle(edges)
    adjacency, adjacency_masks = _make_adjacency(n, edges)

    return {
        "family": "near_threshold_square_hamilton_cycle",
        "n": n,
        "noise_factor_num": noise_factor_num,
        "threshold_scale": "sqrt(e/n)",
        "target_edge_count": target_edges,
        "actual_density": target_edges / total_pairs,
        "vertices": list(range(n)),
        "edges": edges,
        "adjacency": adjacency,
        "adjacency_masks": adjacency_masks,
        "answer": _normalize_cycle(relabel),
    }


