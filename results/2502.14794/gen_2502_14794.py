def parse_answer(text: str) -> object | None:
    if not isinstance(text, str):
        return None
    blocks = re.findall(r"<answer\b[^>]*>(.*?)</answer>", text, flags=re.I | re.S)
    candidates = blocks if blocks else re.findall(
        r"```(?:json)?\s*(.*?)```", text, flags=re.I | re.S
    )
    for raw in reversed(candidates):
        try:
            value = json.loads(raw.strip())
        except (TypeError, ValueError, json.JSONDecodeError):
            continue
        if isinstance(value, list) and all(type(x) is int for x in value):
            return value
    return None


def verify(inst: dict, answer: object) -> tuple[bool, str]:
    """Check any canonical square-Hamilton ordering; never inspect inst['answer']."""
    n = inst["n"]
    if not isinstance(answer, list):
        return False, "answer_not_list"
    if not answer:
        return False, "answer_empty"
    if len(answer) != n:
        return False, f"wrong_length:{len(answer)}_expected_{n}"
    if any(type(v) is not int for v in answer):
        return False, "non_integer_vertex"
    if any(v < 0 or v >= n for v in answer):
        return False, "vertex_out_of_range"
    if len(set(answer)) != n:
        return False, "duplicate_vertex"
    if answer[0] != 0:
        return False, "noncanonical_rotation"
    if answer[1] >= answer[-1]:
        return False, "noncanonical_orientation"

    masks = inst["adjacency_masks"]
    for i, u in enumerate(answer):
        for jump in (1, 2):
            v = answer[(i + jump) % n]
            if not (masks[u] >> v) & 1:
                return False, f"missing_square_edge:{u}-{v}_at_{i}+{jump}"
    return True, "ok"


def random_candidate(inst: dict, rng: random.Random) -> object:
    """Uniformly sample canonical cycles, enforcing all obvious shape rules."""
    tail = list(range(1, inst["n"]))
    rng.shuffle(tail)
    if tail[0] > tail[-1]:
        tail.reverse()
    return [0] + tail


def search_space(inst: dict) -> int | None:
    return math.factorial(inst["n"] - 1) // 2


def enumerate_all(inst: dict) -> int | None:
    if search_space(inst) > 200_000:
        return None
    count = 0
    for tail in itertools.permutations(range(1, inst["n"])):
        if tail[0] >= tail[-1]:
            continue
        if verify(inst, [0] + list(tail))[0]:
            count += 1
    return count


def canonical_key(inst: dict) -> str:
    """Relabelling-invariant WL/edge-profile fingerprint of the host graph."""
    n = inst["n"]
    adjacency = inst["adjacency"]
    masks = inst["adjacency_masks"]
    colors = [len(row) for row in adjacency]
    for _ in range(4):
        signatures = [
            (colors[u], tuple(sorted(colors[v] for v in adjacency[u])))
            for u in range(n)
        ]
        palette = {sig: i for i, sig in enumerate(sorted(set(signatures)))}
        colors = [palette[sig] for sig in signatures]

    vertex_profiles = Counter(colors)
    edge_profiles = Counter()
    for u in range(n):
        for v in adjacency[u]:
            if u < v:
                common = (masks[u] & masks[v]).bit_count()
                edge_profiles[(min(colors[u], colors[v]), max(colors[u], colors[v]), common)] += 1
    payload = json.dumps(
        [
            n,
            len(inst["edges"]),
            sorted(vertex_profiles.items()),
            sorted((list(k), value) for k, value in edge_profiles.items()),
        ],
        separators=(",", ":"),
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


