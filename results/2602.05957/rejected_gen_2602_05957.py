def _det(a: tuple[int, int] | list[int],
         b: tuple[int, int] | list[int]) -> int:
    return a[0] * b[1] - a[1] * b[0]


def _matvec(T: list[list[int]], v: tuple[int, int] | list[int]) -> tuple[int, int]:
    return (T[0][0] * v[0] + T[0][1] * v[1],
            T[1][0] * v[0] + T[1][1] * v[1])


def _primitive(v: tuple[int, int] | list[int]) -> tuple[int, int] | None:
    g = math.gcd(abs(v[0]), abs(v[1]))
    if g == 0:
        return None
    return (v[0] // g, v[1] // g)


def _fibonacci(index: int) -> int:
    a, b = 0, 1
    for _ in range(index):
        a, b = b, a + b
    return a


def _ordered_rays(inst: dict) -> tuple[tuple[int, int], tuple[int, int]]:
    rays = inst.get("cone_rays")
    if (not isinstance(rays, list) or len(rays) != 2
            or any(not isinstance(v, list) or len(v) != 2 for v in rays)):
        raise ValueError("cone_rays must contain two 2-vectors")
    c = (rays[0][0], rays[0][1])
    d = (rays[1][0], rays[1][1])
    if _det(c, d) == 0:
        raise ValueError("cone rays are collinear")
    if _det(c, d) < 0:
        c, d = d, c
    return c, d


def _points(inst: dict) -> list[tuple[int, int]]:
    raw = inst.get("points")
    if (not isinstance(raw, list) or len(raw) < 2
            or any(not isinstance(v, list) or len(v) != 2
                   or any(isinstance(x, bool) or not isinstance(x, int) for x in v)
                   for v in raw)):
        raise ValueError("points must be a list of integer 2-vectors")
    return [(v[0], v[1]) for v in raw]


def _extreme_points(points: list[tuple[int, int]]) -> tuple[tuple[int, int], tuple[int, int]]:
    u = v = points[0]
    for p in points[1:]:
        if _det(p, u) > 0:  # p has lower oriented slope than u
            u = p
        if _det(v, p) > 0:  # p has higher oriented slope than v
            v = p
    return u, v


def make_instance(n: int, seed: int = 0, *, pairs: int = 8,
                  fib_index: int = 9, margin: int = 2, **params: Any) -> dict:
    """Inverse-generate a cone instance and its lattice-split certificate."""
    if isinstance(n, bool) or not isinstance(n, int) or n < 1:
        raise ValueError("n must be a positive integer")
    if isinstance(pairs, bool) or not isinstance(pairs, int) or not 2 <= pairs <= 8:
        raise ValueError("pairs must be an integer in [2,8]")
    if not 3 <= fib_index <= 18:
        raise ValueError("fib_index must be in [3,18]")
    if not 2 <= margin <= 5:
        raise ValueError("margin must be in [2,5]")

    rng = random.Random(seed)
    a = (_fibonacci(fib_index), _fibonacci(fib_index + 1))
    b = (_fibonacci(fib_index + 1), _fibonacci(fib_index + 2))
    if _det(a, b) < 0:
        a, b = b, a

    # A seed-dependent unimodular shear changes the displayed coordinates but
    # preserves primitivity, determinants, the cone problem, and the answer.
    shear = rng.randrange(0, 9)
    T = [[1, 0], [shear, 1]]
    a = _matvec(T, a)
    b = _matvec(T, b)
    c = (margin * a[0] - b[0], margin * a[1] - b[1])
    d = (margin * b[0] - a[0], margin * b[1] - a[1])
    if min(*a, *b, *c, *d) <= 0 or _det(c, a) <= 0 or _det(b, d) <= 0:
        raise ArithmeticError("internal cone construction failed")

    # This optional gvlib check exercises the repo's exact matrix layer without
    # making it a dependency.  All emitted values remain JSON-native integers.
    if exact_matrices is not None:
        basis = exact_matrices.matrix([[a[0], b[0]], [a[1], b[1]]])
        if exact_matrices.det(basis) != 1:
            raise ArithmeticError("hidden generators are not unimodular")
    elif _det(a, b) != 1:
        raise ArithmeticError("hidden generators are not unimodular")

    displayed: list[tuple[int, int]] = []
    coefficients: list[tuple[int, int, int, int]] = []
    used_ratios: set[tuple[int, int]] = set()
    for pair_index in range(pairs):
        # All points come from the same swapped-coefficient construction, but
        # every pair has a different centre.  Coordinate extrema therefore do
        # not automatically disclose a pair.
        attempts = 0
        while True:
            common_sum = (6 * n + 2 * pairs + 1
                          + 2 * rng.randrange(max(2, 3 * n + pair_index + 1)))
            difference = (2 * n + 1
                          + 2 * rng.randrange(max(2, 2 * n + pair_index + 1)))
            if difference < common_sum:
                ratio_gcd = math.gcd(difference, common_sum)
                ratio = (difference // ratio_gcd, common_sum // ratio_gcd)
                if ratio not in used_ratios:
                    used_ratios.add(ratio)
                    break
            attempts += 1
            if attempts > 10_000:
                raise ArithmeticError("could not sample distinct coefficient ratios")
        alpha = (common_sum + difference) // 2
        beta = (common_sum - difference) // 2
        if beta <= 0 or alpha + beta != common_sum:
            raise ArithmeticError("invalid hidden coefficient pair")
        left = (alpha * a[0] + beta * b[0],
                alpha * a[1] + beta * b[1])
        right = (beta * a[0] + alpha * b[0],
                 beta * a[1] + alpha * b[1])
        displayed.extend((left, right))
        coefficients.append((difference, common_sum, alpha, beta))

    rng.shuffle(displayed)
    u, _ = _extreme_points(displayed)
    best = coefficients[0]
    for candidate in coefficients[1:]:
        if candidate[0] * best[1] > best[0] * candidate[1]:
            best = candidate
    _, _, alpha_max, beta_max = best
    expected_u = (alpha_max * a[0] + beta_max * b[0],
                  alpha_max * a[1] + beta_max * b[1])
    if u != expected_u:
        raise ArithmeticError("coefficient extrema do not match cone extrema")
    q = (alpha_max * a[0], alpha_max * a[1])

    return {
        "family": "rank-two affine-semigroup generators",
        "scale": n,
        "cone_rays": [list(c), list(d)],
        "points": [list(p) for p in displayed],
        "answer": {
            "split": list(q),
            "generators": [list(a), list(b)],
        },
    }


