def _validate_params(
    n: int, extra_edges: int | None, decoys: int, disclose: str
) -> tuple[int, int, int, str]:
    if isinstance(n, bool) or not isinstance(n, int) or n < 6:
        raise ValueError("n must be an integer at least 6")
    if extra_edges is None:
        extra_edges = max(5, n)
    if (isinstance(extra_edges, bool) or not isinstance(extra_edges, int)
            or extra_edges < 2):
        raise ValueError("extra_edges must be an integer at least 2")
    if isinstance(decoys, bool) or not isinstance(decoys, int) or decoys < 0:
        raise ValueError("decoys must be a nonnegative integer")
    if disclose not in {"none", "rule", "pages"}:
        raise ValueError("disclose must be 'none', 'rule', or 'pages'")
    if extra_edges > 2 * n - 8:
        raise ValueError("extra_edges is too large for reliable generation")
    return n, extra_edges, decoys, disclose


def _crosses_positions(e: tuple[int, int], f: tuple[int, int]) -> bool:
    a, b = e
    c, d = f
    return (a < c < b < d) or (c < a < d < b)


def _grow_connected_chords(
    n: int, count: int, rng: random.Random
) -> tuple[list[tuple[int, int]], list[int]]:
    """Generate two noncrossing pages whose chord crossing graph is connected."""

    best: tuple[list[tuple[int, int]], list[int]] = ([], [])
    for _restart in range(80):
        pages: list[list[tuple[int, int]]] = [[], []]
        chords: list[tuple[int, int]] = []
        colours: list[int] = []
        seen: set[tuple[int, int]] = set()
        failures = 0
        while len(chords) < count and failures < 20_000:
            left = rng.randrange(0, n - 2)
            right = rng.randrange(left + 2, n)
            edge = (left, right)
            page = (right - left) & 1
            if edge in seen:
                failures += 1
                continue
            if any(_crosses_positions(edge, other) for other in pages[page]):
                failures += 1
                continue
            if chords and not any(
                _crosses_positions(edge, other) for other in pages[1 - page]
            ):
                failures += 1
                continue
            pages[page].append(edge)
            chords.append(edge)
            colours.append(page)
            seen.add(edge)
            failures = 0
        if len(chords) > len(best[0]):
            best = (chords, colours)
        if len(chords) == count:
            return chords, colours
    raise RuntimeError(
        f"could generate only {len(best[0])}/{count} connected chords"
    )


def _crossing_pairs(
    order: list[int], edges: list[list[int]]
) -> list[list[int]]:
    pos = {vertex: i for i, vertex in enumerate(order)}
    normalized = [(pos[u], pos[v]) for u, v in edges]
    pairs: list[list[int]] = []
    for i, edge in enumerate(normalized):
        for j in range(i):
            if _crosses_positions(edge, normalized[j]):
                pairs.append([j, i])
    return pairs


def _colours_to_answer(colours: list[int]) -> list[int]:
    page_zero = [i for i, colour in enumerate(colours) if colour == 0]
    page_one = [i for i, colour in enumerate(colours) if colour == 1]
    return page_zero + [-1] + page_one


def _valid_colours(inst: dict, colours: list[int]) -> bool:
    if len(colours) != inst["m"]:
        return False
    return all(colours[i] != colours[j] for i, j in inst["crossings"])


def _attack_colourings(inst: dict) -> dict[str, list[int]]:
    pos = {vertex: i for i, vertex in enumerate(inst["order"])}
    lengths = [pos[v] - pos[u] for u, v in inst["edges"]]
    ordered_lengths = sorted(lengths)
    median = ordered_lengths[len(ordered_lengths) // 2]

    outlier = [int(length > median) for length in lengths]
    raw_parity = [length & 1 for length in lengths]
    alternating = [i & 1 for i in range(inst["m"])]

    adjacency: list[list[int]] = [[] for _ in range(inst["m"])]
    for i, j in inst["crossings"]:
        adjacency[i].append(j)
        adjacency[j].append(i)
    online = [-1] * inst["m"]
    for edge_id in range(inst["m"]):
        used = {online[j] for j in adjacency[edge_id]
                if j < edge_id and online[j] >= 0}
        if 0 not in used:
            online[edge_id] = 0
        elif 1 not in used:
            online[edge_id] = 1
        else:
            # First-fit has failed; retain a total candidate for the verifier.
            online[edge_id] = 0
    return {
        "outlier_short_vs_long": outlier,
        "greedy_online_first_fit": online,
        "alternating_input_rows": alternating,
        "raw_spine_span_parity": raw_parity,
    }


def make_instance(
    n: int,
    seed: int = 0,
    extra_edges: int | None = None,
    decoys: int = 0,
    disclose: str = "none",
) -> dict:
    """Construct a fixed-spine two-page instance and its known certificate."""

    n, extra_edges, decoys, disclose = _validate_params(
        n, extra_edges, decoys, disclose
    )
    rng = random.Random(seed)

    # The adjacent edges activate every compressed-spine vertex and never cross.
    base_edges = [(i, i + 1) for i in range(n - 1)]
    base_colours = [1] * (n - 1)

    # Retry only the random construction choices and cheap attack filters.  The
    # planted pages are known throughout; no witness search occurs here.
    for _outer in range(160):
        chords, chord_colours = _grow_connected_chords(n, extra_edges, rng)
        core_edges = base_edges + chords
        core_colours = base_colours + chord_colours

        total_vertices = n + decoys
        active_positions = sorted(rng.sample(range(total_vertices), n))
        core_to_position = dict(enumerate(active_positions))

        labels = rng.sample(range(1000, 1000 + 50 * total_vertices), total_vertices)
        order = list(labels)
        labelled_edges = [
            [labels[core_to_position[u]], labels[core_to_position[v]]]
            for u, v in core_edges
        ]

        row_order = list(range(len(labelled_edges)))
        if disclose == "pages":
            # The easy rung exposes the page split explicitly and keeps each
            # page contiguous, so the oracle ladder has a genuinely easy start.
            zeros = [i for i, c in enumerate(core_colours) if c == 0]
            ones = [i for i, c in enumerate(core_colours) if c == 1]
            rng.shuffle(zeros)
            rng.shuffle(ones)
            row_order = zeros + ones
        else:
            rng.shuffle(row_order)

        edges = [labelled_edges[i] for i in row_order]
        colours = [core_colours[i] for i in row_order]
        crossings = _crossing_pairs(order, edges)
        inst = {
            "n": n,
            "extra_edges": extra_edges,
            "decoys": decoys,
            "disclose": disclose,
            "order": order,
            "edges": edges,
            "m": len(edges),
            "crossings": crossings,
            "page_zero_prefix": (
                sum(1 for colour in colours if colour == 0)
                if disclose == "pages" else None
            ),
            "answer": _colours_to_answer(colours),
        }
        if disclose != "none":
            return inst
        if all(
            not _valid_colours(inst, candidate)
            for candidate in _attack_colourings(inst).values()
        ):
            return inst
    raise RuntimeError("could not defeat the deterministic cheap attacks")


