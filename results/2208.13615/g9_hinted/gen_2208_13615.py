def parse_answer(text: str) -> object | None:
    """Parse the canonical JSON list from a tagged model response."""

    if not isinstance(text, str):
        return None
    match = _ANSWER_RE.search(text)
    if match is None:
        return None
    payload = match.group(1).strip()
    if payload.startswith("```"):
        payload = re.sub(r"^```(?:json|python|text)?\s*", "", payload, flags=re.I)
        payload = re.sub(r"\s*```$", "", payload)
    try:
        value = json.loads(payload)
    except (TypeError, ValueError):
        return None
    if not isinstance(value, list):
        return None
    if any(isinstance(v, bool) or not isinstance(v, int) for v in value):
        return None
    return value


def _answer_to_colours(inst: dict, answer: object) -> tuple[list[int] | None, str]:
    if not isinstance(answer, list):
        return None, "answer must be a JSON integer list"
    if not answer:
        return None, "answer list is empty"
    if len(answer) != inst["m"] + 1:
        return None, f"expected exactly {inst['m'] + 1} list entries"
    if any(isinstance(v, bool) or not isinstance(v, int) for v in answer):
        return None, "every list entry must be an integer"
    if any(v < -1 or v >= inst["m"] for v in answer):
        return None, f"edge ID outside the allowed range -1..{inst['m'] - 1}"
    if answer.count(-1) != 1:
        return None, "separator -1 must occur exactly once"
    edge_ids = [v for v in answer if v != -1]
    if len(set(edge_ids)) != len(edge_ids):
        return None, "an edge ID is duplicated"
    if set(edge_ids) != set(range(inst["m"])):
        return None, "the partition omits at least one edge ID"
    separator = answer.index(-1)
    if answer[:separator] != sorted(answer[:separator]):
        return None, "page-0 edge IDs are not strictly increasing"
    if answer[separator + 1:] != sorted(answer[separator + 1:]):
        return None, "page-1 edge IDs are not strictly increasing"
    colours = [1] * inst["m"]
    for edge_id in answer[:separator]:
        colours[edge_id] = 0
    return colours, "ok"


def verify(inst: dict, answer: object) -> tuple[bool, str]:
    """Check a proposed page partition without consulting inst['answer']."""

    colours, reason = _answer_to_colours(inst, answer)
    if colours is None:
        return False, reason
    for i, j in inst.get("crossings") or _crossing_pairs(
        inst["order"], inst["edges"]
    ):
        if colours[i] == colours[j]:
            return False, f"same-page crossing between edge IDs {i} and {j}"
    return True, "ok"


def random_candidate(inst: dict, rng: random.Random) -> object:
    """Sample uniformly from all canonical two-page edge partitions."""

    colours = [rng.randrange(2) for _ in range(inst["m"])]
    return _colours_to_answer(colours)


def search_space(inst: dict) -> int | None:
    """Return the exact number of canonical page partitions."""

    return 1 << inst["m"]


def enumerate_all(inst: dict) -> int | None:
    """Brute-force all partitions when the declared cap permits it."""

    space = search_space(inst)
    if space is None or space > _ENUMERATION_CAP:
        return None
    valid = 0
    for mask in range(space):
        colours = [(mask >> i) & 1 for i in range(inst["m"])]
        valid += int(_valid_colours(inst, colours))
    return valid


def _crossing_component_count(inst: dict) -> int:
    adjacency: list[list[int]] = [[] for _ in range(inst["m"])]
    for i, j in inst["crossings"]:
        adjacency[i].append(j)
        adjacency[j].append(i)
    seen: set[int] = set()
    components = 0
    for start in range(inst["m"]):
        if start in seen:
            continue
        components += 1
        seen.add(start)
        stack = [start]
        while stack:
            edge_id = stack.pop()
            for neighbor in adjacency[edge_id]:
                if neighbor not in seen:
                    seen.add(neighbor)
                    stack.append(neighbor)
    return components


def _reference_algorithm(inst: dict) -> tuple[list[int] | None, dict[str, int]]:
    """Build the crossing graph explicitly and bipartite-colour it."""

    m = inst["m"]
    pos = {vertex: i for i, vertex in enumerate(inst["order"])}
    intervals = [(pos[u], pos[v]) for u, v in inst["edges"]]
    adjacency: list[list[int]] = [[] for _ in range(m)]
    pair_tests = 0
    crossing_edges = 0
    for i in range(m):
        for j in range(i):
            pair_tests += 1
            if _crosses_positions(intervals[i], intervals[j]):
                adjacency[i].append(j)
                adjacency[j].append(i)
                crossing_edges += 1

    colours = [-1] * m
    bfs_steps = 0
    for start in range(m):
        if colours[start] >= 0:
            continue
        colours[start] = 0
        queue = [start]
        cursor = 0
        while cursor < len(queue):
            edge_id = queue[cursor]
            cursor += 1
            bfs_steps += 1
            for neighbor in adjacency[edge_id]:
                bfs_steps += 1
                if colours[neighbor] < 0:
                    colours[neighbor] = colours[edge_id] ^ 1
                    queue.append(neighbor)
                elif colours[neighbor] == colours[edge_id]:
                    return None, {
                        "pair_tests": pair_tests,
                        "crossing_edges": crossing_edges,
                        "bfs_steps": bfs_steps,
                    }
    return _colours_to_answer(colours), {
        "pair_tests": pair_tests,
        "crossing_edges": crossing_edges,
        "bfs_steps": bfs_steps,
    }


def _structural_decode(inst: dict) -> list[int]:
    """Use the compressed-spine parity invariant."""

    incident = {vertex for edge in inst["edges"] for vertex in edge}
    active = [vertex for vertex in inst["order"] if vertex in incident]
    rank = {vertex: i for i, vertex in enumerate(active)}
    colours = [(rank[v] - rank[u]) & 1 for u, v in inst["edges"]]
    return _colours_to_answer(colours)


def canonical_key(inst: dict) -> str:
    """Canonicalize vertex names and edge-row order through spine positions."""

    position = {vertex: i for i, vertex in enumerate(inst["order"])}
    normalized_edges = sorted(
        (position[u], position[v]) for u, v in inst["edges"]
    )
    payload = {
        "spine_vertices": len(inst["order"]),
        "directed_position_edges": normalized_edges,
    }
    blob = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


